-- =============================================================================
-- 0058_orders_payment_initiated_at.sql  (гонка «оплатил → вернулся раньше колбэка»)
-- Время ПОСЛЕДНЕЙ инициации платежа по заказу — единственный серверный факт,
-- по которому витрина может отличить «ещё не платил» от «уже платит прямо сейчас».
--
-- ЗАЧЕМ (денежный дефект). Покупатель уходит на шлюз, платит и возвращается на
-- страницу успеха БЫСТРЕЕ, чем приходит вебхук: payment_status ещё 'pending'.
-- Страница показывала «ожидает оплаты» и кнопку «оплатить» — второй платёж.
-- Отличить этот случай от честного «закрыл вкладку, не заплатив» можно только по
-- ФАКТУ инициации и её ВРЕМЕНИ:
--   * orders.payment_ref (0012) отвечает «счёт выставляли», но БЕЗ времени — по
--     нему кнопку пришлось бы прятать НАВСЕГДА (новый тупик);
--   * orders.updated_at меняет ЛЮБАЯ правка заказа (смена статуса оператором,
--     трек СДЭК) — как «время инициации платежа» он врёт;
--   * *_payment_log (0027/0037/0052) пишутся на КОЛБЭК/сверку, а не на инициацию —
--     ровно в спорном окне строки ещё нет.
-- Отсюда — отдельная колонка, которую ставят все провайдеры при выставлении счёта.
--
-- Решения:
--   * NULL-able БЕЗ DEFAULT: у заказов до этой миграции инициация не зафиксирована;
--     NULL честно означает «неизвестно» → витрина ведёт себя как раньше (кнопка
--     оплаты доступна), новых тупиков миграция не создаёт.
--   * Ставится при КАЖДОЙ инициации (в т.ч. повторной) вместе с payment_ref —
--     окно ожидания подтверждения отсчитывается от последней попытки.
--   * Провайдеро-НЕЗАВИСИМА (paykeeper/tbank/alfabank и любой будущий): значение
--     пишет общий шаг «сохранить payment_ref», а не код конкретного эквайринга.
--   * Публичный DTO отдаёт её как paymentInitiatedAt (ISO). Это НЕ утечка:
--     сам payment_ref наружу по-прежнему не уходит, а факт «вы только что начали
--     оплату» покупателю и так известен — он предъявил токен своего заказа.
--   * GRANT: права в 0012 выданы НА ТАБЛИЦУ orders целиком, табличная привилегия
--     PostgreSQL распространяется на добавленные позже колонки.
--
-- Идемпотентно и АДДИТИВНО (проходит scripts/check-migrations.sh):
--   ADD COLUMN IF NOT EXISTS; schema_migrations — ON CONFLICT DO NOTHING.
--   НЕТ DROP/RENAME/смены типа/DROP CONSTRAINT.
-- =============================================================================

ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_initiated_at timestamptz;

COMMENT ON COLUMN orders.payment_initiated_at IS 'Время последней инициации платежа (выставления счёта) по заказу; NULL — не инициировался';

INSERT INTO schema_migrations (version, name)
VALUES ('0058', 'orders_payment_initiated_at')
ON CONFLICT DO NOTHING;
