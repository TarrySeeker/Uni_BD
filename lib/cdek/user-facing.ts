/**
 * Какие доменные отказы СДЭК показывать ОПЕРАТОРУ (а какие прятать в лог).
 *
 * Вынесено из actions.ts, потому что тот помечен `'use server'` и может
 * экспортировать только async-функции (набор/предикат — не функции-действия).
 *
 * ЗАЧЕМ (аудит 2026-07-26, находка №32). Осмысленные отказы («PDF ещё не готов —
 * повторите», «отмену посылки в пути надо оформлять возвратом», «создание уже
 * выполняется другим процессом», «статус изменился во время отмены — нужна ручная
 * сверка») не входили в набор, поэтому defineAction сворачивал их в
 * { ok:false, error:'internal' } и оператор читал безликое «Не удалось выполнить
 * операцию. Попробуйте ещё раз.» — совет заведомо вредный: повтор не поможет
 * НИКОГДА, а что делать вместо отмены, не сказано.
 *
 * ГРАНИЦА. Сюда попадает только то, что описывает БИЗНЕС-ПРАВИЛО или состояние
 * заказа — такой текст безопасен и полезен. Транспортные/технические коды
 * (`cdek_auth_failed`, `cdek_network_error`, `cdek_http_error` с сырым ответом
 * СДЭК) остаются внутренними: их сообщения могут нести детали интеграции и
 * ничего не говорят оператору о том, что делать.
 */

import { CdekError } from './errors';

/** Коды CdekError, чьё сообщение безопасно и полезно показать оператору. */
export const USER_FACING_CDEK_CODES: ReadonlySet<string> = new Set([
  // Бизнес-предусловия создания накладной.
  'cdek_precondition_failed',
  'cdek_missing_pvz',
  'cdek_invalid_phone',
  'cdek_no_shipment',
  // Состояние процесса — повтор либо бессмыслен, либо требует паузы/другого действия.
  'cdek_create_in_progress',
  'cdek_cancel_not_allowed',
  'cdek_cancel_raced',
  'cdek_print_not_ready',
  // Модуль выключен в настройках магазина — это конфигурация, а не сбой.
  'module_disabled',
]);

/** Показывать ли текст этой ошибки оператору (иначе — только в лог сервера). */
export function isUserFacingCdekCode(err: unknown): boolean {
  return err instanceof CdekError && USER_FACING_CDEK_CODES.has(err.code);
}
