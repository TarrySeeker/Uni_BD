/** Доменная причина отказа Storefront API. */
export type StorefrontErrorReason = (typeof STOREFRONT_ERROR_REASONS)[number];

const REASON_SET: ReadonlySet<string> = new Set(STOREFRONT_ERROR_REASONS);

/** Принадлежит ли значение публичному алфавиту причин (защита от опечаток). */
export function isStorefrontErrorReason(value: unknown): value is StorefrontErrorReason {
  return typeof value === 'string' && REASON_SET.has(value);
}

/**
 * Транспортный код (и, через него, HTTP-статус) для доменной причины.
 *
 * 409 conflict — конфликт состояния (остаток кончился, заказ уже оплачен):
 * повтор ТОГО ЖЕ запроса не поможет, нужно менять корзину/действие.
 * 422 unprocessable — данные домена невалидны при синтаксически верном теле.
 * 404 намеренно НЕ используется для order_not_found: единый ответ «не найдено»
 * зеркалит поведение роутов заказа (перебор номеров не должен различать
 * «нет заказа» и «нет доступа») — этот случай роут отдаёт своим кодом сам.
 */
export function transportForReason(
  reason: StorefrontErrorReason,
): 'conflict' | 'unprocessable' {
  const conflicts: readonly StorefrontErrorReason[] = [
    'out_of_stock',
    'order_not_payable',
    // Холд уже стоит — это конфликт состояния заказа, а не плохие данные.
    'payment_in_progress',
    // Тело валидно; разошлось СОСТОЯНИЕ (цена/промокод/остаток сертификата/уже
    // созданный заказ). Повтор ТОГО ЖЕ запроса не поможет — нужен свежий расчёт.
    'total_mismatch',
  ];
  return conflicts.includes(reason) ? 'conflict' : 'unprocessable';
}

/**
 * ДОМЕННАЯ ПРИЧИНА ОТКАЗА ОПЛАТЫ → публичная причина Storefront API.
 *
 * Живёт здесь (а не в домене): `lib/orders/status.ts` не должен знать про
 * публичный контракт витрины, а три init-роута не должны каждый по-своему
 * решать, каким кодом отвечать. Направление зависимости — «презентация знает
 * домен», импорт типа стирается при компиляции.
 *
 * 🔴 `funds_held` НЕ схлопывается в `order_not_payable`: «деньги удержаны, ждём
 * подтверждения» и «заказ оплатить нельзя» — разные сообщения для покупателя,
 * и подмена первого вторым провоцирует повторные попытки оплаты.
 */
export function reasonForPaymentBlock(block: PaymentBlock): StorefrontErrorReason {
  return block === 'funds_held' ? 'payment_in_progress' : 'order_not_payable';
}

