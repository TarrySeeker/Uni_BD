-- =============================================================================
-- 0057_users_ui_locale.sql  (i18n админки — предпочтительный язык ИНТЕРФЕЙСА)
-- Хранит выбранный оператором язык панели управления (next-intl foundation).
--
-- Решения:
--   * users.ui_locale — язык ИНТЕРФЕЙСА админки конкретного пользователя
--     ('ru' | 'en' | 'fr'), НЕЗАВИСИМ от shop_settings.i18n (набор языков ВИТРИНЫ).
--     Язык панели — предпочтение оператора, а не настройка магазина. Дублирует
--     cookie NEXT_LOCALE для устойчивого предпочтения между устройствами/сессиями.
--   * NULL-able БЕЗ DEFAULT: у существующих пользователей предпочтения ещё нет;
--     NULL → фолбэк на язык по умолчанию (admin/'ru') в i18n/request.ts. Отсутствие
--     DEFAULT осознанно — платформа не навязывает язык, выбор делает оператор.
--   * НЕТ CHECK на значение: набор языков интерфейса задаётся кодом (messages/*.json
--     + ADMIN_LOCALE_CONFIG) и валидируется на входе (resolveAdminLocale). БД-CHECK
--     пришлось бы расширять при каждом новом языке перевода — валидацию держим в
--     приложении, колонку оставляем свободной. Никакого widening существующего
--     CHECK здесь нет (carve-out ADR-P1-2 не требуется).
--   * GRANT: права в 0012 выданы НА ТАБЛИЦУ users целиком, табличная привилегия
--     PostgreSQL распространяется на добавленные позже колонки. Отдельный GRANT
--     на новую колонку не нужен.
--
-- Идемпотентно и АДДИТИВНО (проходит scripts/check-migrations.sh):
--   ADD COLUMN IF NOT EXISTS; schema_migrations — ON CONFLICT DO NOTHING.
--   НЕТ DROP/RENAME/смены типа/DROP CONSTRAINT.
-- =============================================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS ui_locale text;

COMMENT ON COLUMN users.ui_locale IS 'Предпочтительный язык интерфейса админки оператора (ru|en|fr); NULL — язык по умолчанию';

INSERT INTO schema_migrations (version, name)
VALUES ('0057', 'users_ui_locale')
ON CONFLICT DO NOTHING;
