/**
 * Константы личного кабинета покупателя.
 *
 * Модуль намеренно БЕЗ зависимостей (как `lib/auth/constants.ts`): его
 * импортируют и серверные роуты, и слой витрины, и тесты — он не должен тянуть
 * за собой ни драйвер БД, ни Next.
 *
 * Значения здесь — контракт между API платформы (валидирует сессию) и витриной
 * (хранит токен в cookie и передаёт его заголовком). Расхождение имён между
 * сторонами ломает вход молча: запрос уходит без токена, API отвечает «не
 * авторизован», и выглядит это как «кабинет не работает».
 */

/**
 * Срок жизни сессии покупателя — 30 дней.
 *
 * Заметно дольше админской: покупатель заходит редко, и разлогинивать его между
 * покупками — верный способ обесценить кабинет. Риск ниже, чем у сотрудника:
 * у покупателя нет доступа ни к чужим данным, ни к настройкам магазина.
 */
export const CUSTOMER_SESSION_TTL_MS = 30 * 24 * 60 * 60 * 1000;

/**
 * Порог скользящего продления: сессию продлеваем, когда до конца осталось меньше
 * половины срока.
 *
 * Почему не при каждом запросе: продление — это запись в базу, а обращений к
 * кабинету много. Порог даёт «вечную» сессию для активного покупателя ценой
 * одной записи раз в две недели.
 */
export const CUSTOMER_SESSION_REFRESH_THRESHOLD_MS = CUSTOMER_SESSION_TTL_MS / 2;

/**
 * Заголовок, которым витрина передаёт токен сессии в API платформы.
 *
 * Клиентскому JS токен не виден никогда: он лежит в httpOnly-cookie на домене
 * витрины, а серверная часть витрины перекладывает его в этот заголовок. Так XSS
 * на витрине не уводит сессию покупателя.
 */
export const CUSTOMER_SESSION_HEADER = 'x-customer-session';

/**
 * Имя httpOnly-cookie покупателя. Нейтральное — тематика магазина в код не
 * попадает (в одном из магазинов сюда уехало имя чужого бренда при копировании).
 */
export const CUSTOMER_SESSION_COOKIE = 'admik_customer_session';

/** Минимальная длина пароля покупателя (минимум OWASP для потребительских ЛК). */
export const CUSTOMER_PASSWORD_MIN = 8;

/**
 * Максимальная длина пароля.
 *
 * Ограничение не «на всякий случай»: argon2 считает хеш от всего ввода, и без
 * верхней границы мегабайтный «пароль» превращается в способ занять процессор
 * сервера одним запросом.
 */
export const CUSTOMER_PASSWORD_MAX = 128;

/**
 * Срок жизни ссылки восстановления пароля — 1 час.
 *
 * Короткий намеренно: письмо может остаться в открытом почтовом ящике, а ссылка
 * даёт полный доступ к аккаунту.
 */
export const CUSTOMER_RESET_TOKEN_TTL_MS = 60 * 60 * 1000;

/**
 * Срок жизни ссылки подтверждения адреса — 48 часов.
 *
 * Длиннее, чем у сброса пароля: подтверждение обычно откладывают «на потом», а
 * цена просроченной ссылки здесь — всего лишь повторная отправка письма.
 */
export const CUSTOMER_VERIFY_TOKEN_TTL_MS = 48 * 60 * 60 * 1000;

/**
 * Ограничение частоты для операций кабинета.
 *
 * Вёдра у покупателей и сотрудников РАЗДЕЛЬНЫЕ: при общем ключе всплеск
 * покупательского трафика выбивал бы владельца из админки.
 *
 * Лимит применяется в сервисном слое, а не в отдельных роутах. Разница не
 * косметическая: в одной из реализаций защиту прикрутили только к входу и
 * регистрации, а подтверждение адреса и повторная отправка письма остались
 * открытыми — то есть перебор токена и рассылка писем на чужой адрес.
 */
export const CUSTOMER_AUTH_RATE_LIMIT = {
  /** Окно наблюдения. */
  windowMs: 15 * 60 * 1000,
  /** Попыток с одного адреса за окно. */
  maxPerIp: 20,
  /** Попыток по одному email за окно (защита конкретного аккаунта). */
  maxPerEmail: 5,
} as const;
