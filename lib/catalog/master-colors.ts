/**
 * Разрешает справочник для магазина: валидный оверрайд из настроек или дефолт.
 *
 * Оверрайд считается заданным, если после отбраковки битых записей (пустой id/name,
 * невалидный hex) осталась хотя бы одна — иначе молча падаем на дефолт, чтобы
 * кривая строка в JSONB не оставила админку без справочника.
 */
export function resolveMasterColors(
  override?: readonly Partial<MasterColor>[] | null,
): MasterColor[] {
  const cleaned: MasterColor[] = [];
  const seen = new Set<string>();
  for (const item of override ?? []) {
    const id = typeof item?.id === 'string' ? item.id.trim() : '';
    const name = typeof item?.name === 'string' ? item.name.trim() : '';
    const hex = normalizeHex(item?.hex);
    if (!id || !name || !hex || seen.has(id)) continue;
    seen.add(id);
    cleaned.push({ id, name, hex });
  }
  return cleaned.length > 0 ? cleaned : DEFAULT_MASTER_COLORS.map((c) => ({ ...c }));
}
