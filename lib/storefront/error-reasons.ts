/**
 * ПУБЛИЧНЫЙ АЛФАВИТ доменных причин отказа Storefront API (контракт платформы).
 *
 * ЗАЧЕМ (аудит 2026-07-26, находки №3 и №6). Сервер знает ТОЧНУЮ причину отказа
 * («нет остатка», «промокод недействителен», «доставка не рассчитана»), но в тело
 * ответа попадал только ТРАНСПОРТНЫЙ код (`conflict`/`unprocessable`) — доменный
 * терялся. Витрина не могла различить причины, карта переводов не срабатывала ни
 * разу, и покупателю на /en и /fr печаталась русская серверная строка.
 *
 * КОНТРАКТ (расширение строго АДДИТИВНОЕ):
 *   • `error.code` — ТРАНСПОРТНЫЙ код (HTTP-семантика). НЕ меняется: на него уже
 *     опираются другие тенанты/потребители.
 *   • `error.reason` — НЕОБЯЗАТЕЛЬНОЕ поле с доменной причиной из этого алфавита.
 *     Старый клиент его просто игнорирует; новый читает приоритетно.
 *
 * ПРАВИЛО ЛОКАЛИЗАЦИИ: `reason` — машинный ключ, витрина сама выбирает по нему
 * строку своего словаря. `message` остаётся диагностикой (лог/поддержка) и НЕ
 * предназначен для показа покупателю (он на языке магазина, не покупателя).
 *
 * Мультитенантность: набор нейтрален к нише магазина — это причины отказа
 * оформления, а не тексты. Новые причины добавляются В КОНЕЦ массива; удаление
 * члена = ломающее изменение контракта (запрещено).
 */

