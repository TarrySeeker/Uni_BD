/**
 * Валюта заказа — ЕДИНЫЙ источник истины (аудит №32, major, деньги).
 *
 * ДЕФЕКТ. Показ цен на витрине шёл из ЭФФЕКТИВНЫХ настроек магазина
 * (`lib/config/settings.ts`: `code: currency.code ?? env.SHOP_CURRENCY` — БД
 * приоритетна), а заказ писался из ENV: `quoteCart` брал `env.SHOP_CURRENCY`, и
 * INSERT заказа подставлял `${env.SHOP_CURRENCY}` напрямую, минуя эффективные
 * настройки. Конвертации между ними не было никакой. Итог: владелец меняет базовую
 * валюту в админке — весь сайт показывает новую, а заказ, квитанция и платёж
 * уходят в старой ПРИ ТОМ ЖЕ ЧИСЛЕ. Покупатель видит цену в одной валюте, платит в
 * другой.
 *
 * РЕШЕНИЕ — КОНСЕРВАТИВНОЕ, без тихой конвертации.
 *
 * 1. Один резолвер на обе точки (котировка корзины и создание заказа). Он читает
 *    ту же самую `EffectiveSettings.currency.code`, что и показ цен, поэтому
 *    расхождение «показ ≠ заказ» становится структурно невозможным: разъехаться
 *    двум значениям больше негде — источник физически один.
 *
 * 2. Суммы НЕ пересчитываются. Цены товаров, пороги доставки, номиналы
 *    сертификатов хранятся в базовой валюте магазина числами; курса смены базовой
 *    валюты платформа не знает и знать не может (это решение владельца, а не
 *    рыночная котировка — доп.валюты в `exchange` служат только ОТОБРАЖЕНИЮ).
 *    Умножить суммы «на глазок» значило бы переоценить весь каталог наугад, то
 *    есть тихо изменить цены — худший из возможных исходов для денег. Поэтому
 *    смена базовой валюты трактуется как переименование единицы измерения: числа
 *    те же, ярлык новый, и он теперь одинаков на экране и в заказе.
 *
 * 3. Существующие заказы НЕ трогаются. `orders.currency` — СНИМОК на момент
 *    заказа (ADR-010), он уже записан в БД и остаётся как есть; резолвер влияет
 *    только на НОВЫЕ заказы. Миграция не нужна: колонка есть и заполнена.
 *
 * 4. Валюта нормализуется к канону ISO-4217 (trim + верхний регистр). Иначе 'rub'
 *    из настроек и 'RUB' из env дали бы в снимках заказов две «разные» валюты,
 *    которые ломают группировку/отчётность, оставаясь одной и той же валютой.
 *
 * 5. Пустого дефолта НЕТ. Нет валюты ни в настройках, ни в env — бросаем. Магазин
 *    без валюты не может принимать заказы, а захардкоженный ₽ увёл бы чужой
 *    магазин платформы не туда (мультитенантность).
 */

/** Часть эффективных настроек, из которой берётся валюта (структурная типизация). */
export interface OrderCurrencySettings {
  currency?: { code?: unknown };
}

/** Часть env, из которой берётся фолбэк валюты. */
export interface OrderCurrencyEnv {
  SHOP_CURRENCY?: unknown;
}

/** Осмысленный код валюты или undefined (пусто/пробелы/не строка → «значения нет»). */
function meaningfulCode(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined;
  const trimmed = value.trim();
  return trimmed === '' ? undefined : trimmed.toUpperCase();
}

/** Отказ резолва валюты: магазин не настроен, заказ принимать нельзя. */
export class MissingShopCurrencyError extends Error {
  constructor() {
    super(
      'Валюта магазина не настроена: нет ни shop_settings.currency.code, ни SHOP_CURRENCY. ' +
        'Заказ не может быть создан без валюты.',
    );
    this.name = 'MissingShopCurrencyError';
  }
}

/**
 * Валюта заказа: эффективные настройки магазина (БД) → env-фолбэк → отказ.
 *
 * Тот же порядок приоритетов, что у `mergeSettings` для ПОКАЗА цен
 * (`currency.code ?? env.SHOP_CURRENCY`) — намеренно: именно совпадение порядка и
 * гарантирует, что покупатель платит в той валюте, которую видел.
 *
 * Устойчив к version skew настроек: нет объекта / нет секции `currency` / поле
 * чужого типа — всё это «значения нет», и работает env-фолбэк, а не TypeError в
 * пути создания заказа.
 *
 * @throws {MissingShopCurrencyError} валюты нет ни в настройках, ни в env.
 */
export function resolveOrderCurrency(
  settings: OrderCurrencySettings | null | undefined,
  env: OrderCurrencyEnv | null | undefined,
): string {
  const fromSettings = meaningfulCode(settings?.currency?.code);
  if (fromSettings) return fromSettings;

  const fromEnv = meaningfulCode(env?.SHOP_CURRENCY);
  if (fromEnv) return fromEnv;

  throw new MissingShopCurrencyError();
}
