/**
 * Дефолты контента главной страницы витрины (ADR-018).
 *
 * Источник правды для ФОЛБЭКА: пока владелец не отредактировал блок главной
 * через админку, витрина показывает этот нейтральный «коробочный» контент.
 * Литералы намеренно обобщённые (без привязки к нише/бренду магазина) — это
 * заглушка-плейсхолдер, которую любой магазин переопределяет под себя.
 *
 * ВАЖНО (мультитенантность): эти значения — нейтральный дефолт платформы, а НЕ
 * хардкод конкретного магазина. Любой магазин переопределяет блоки через ключ
 * настроек `home` (shop_settings) без правки кода. Изображения здесь не заданы
 * (imageKey пуст) — витрина использует собственные ассеты, пока ключ не загружен.
 *
 * Семантика merge: строка БД хранит оверрайд блока ЦЕЛИКОМ; отсутствие блока в
 * БД → берётся соответствующий блок отсюда (см. mergeSettings в config/settings).
 */

/** Полностью разрешённый контент главной (все блоки заполнены, без undefined). */
export interface HomeContent {
  hero: {
    title: string | null;
    subtitle: string | null;
    /** Ключ S3 фонового изображения (не URL); пусто → ассет витрины. */
    imageKey: string | null;
    ctaLabel: string | null;
    ctaHref: string | null;
  };
  about: {
    title: string;
    paragraphs: string[];
    /** Ключи S3 изображений галереи «О бренде» (не URL). */
    imageKeys: string[];
    /** Короткие «ценности»-теги (ValuesStrip / список под галереей). */
    values: string[];
  };
  quality: {
    title: string;
    items: string[];
  };
  delivery: {
    items: { title: string; text: string }[];
  };
  /**
   * Лента ценностей (opt-in): три коротких тезиса title+text. По умолчанию
   * СКРЫТА (enabled:false) — магазин включает её и правит слова в админке без
   * кода. Не путать с about.values (теги-чипы под галереей).
   */
  valuesStrip: {
    enabled: boolean;
    items: { title: string; text: string }[];
  };
  /** Блок «Философия»: надзаголовок, заголовок, абзац и ссылка. */
  philosophy: {
    eyebrow: string;
    title: string;
    text: string;
    linkLabel: string;
    linkHref: string;
  };
  /**
   * Блок «Образы» (lookbook, ТЗ_2 → v2): заголовок + ВКЛАДКИ-КАТЕГОРИИ + КАРУСЕЛЬ
   * КАРТОЧЕК «автор + фото». По умолчанию СКРЫТ и пуст — магазин наполняет его в
   * админке без кода (универсально, без привязки к нише).
   *
   * categories — вкладки-фильтры: `id` (машинный ключ связи с карточками, merge
   * автогенерирует его для легаси) + `title`. Поля `text`/`imageKey` — НАСЛЕДИЕ
   * v1 (статичная сетка): сохраняются, чтобы контент уже работающих магазинов не
   * пропал; в v2-рендере не используются.
   *
   * items — карточки карусели: `categoryId` (какой вкладке принадлежит),
   * `imageKey` (вертикальное фото образа), `authorName`, `authorAvatarKey`.
   */
  looks: {
    enabled: boolean;
    title: string;
    categories: { id: string; title: string; text: string; imageKey: string }[];
    items: {
      categoryId: string;
      imageKey: string;
      authorName: string;
      authorAvatarKey: string;
    }[];
  };
  /**
   * Блок «Плитки категорий» (adaptive tiles, .dop-links--adaptive): список
   * плиток title + ссылка + фото (imageKey S3, не URL). По умолчанию СКРЫТ и
   * пуст — магазин наполняет его в админке без кода (универсально, без ниши).
   */
  tiles: {
    enabled: boolean;
    items: { title: string; href: string; imageKey: string }[];
  };
  /**
   * Блок «Видео» (embed, .mainpage--video): один https-URL для iframe (Vimeo/
   * YouTube-embed и т.п.). По умолчанию СКРЫТ и пуст. Только https (анти-XSS:
   * src iframe не должен принять javascript:/data: — валидируется схемой).
   */
  video: {
    enabled: boolean;
    embedUrl: string;
  };
  /**
   * Блок «Дизайнеры» (showcase, .mainpage--designers): опц. заголовок + список
   * дизайнеров, каждый = имя + ссылка + аватар/работа (ключи S3, не URL) + два
   * коэффициента вертикального позиционирования фото (0..100). По умолчанию
   * СКРЫТ и пуст — магазин наполняет его в админке без кода.
   */
  designers: {
    enabled: boolean;
    title: string;
    items: {
      name: string;
      href: string;
      avatarImageKey: string;
      workImageKey: string;
      avatarTop: number;
      workTop: number;
    }[];
  };
  /**
   * Блок «Промо-слайдер» (.mainpage--slider): список слайдов, каждый = фон
   * (imageKey S3, не URL) + ссылка + имя + подпись (name/caption могут быть
   * пустыми). По умолчанию СКРЫТ и пуст — магазин наполняет его в админке без кода.
   */
  slider: {
    enabled: boolean;
    slides: { imageKey: string; href: string; name: string; caption: string }[];
  };
  /**
   * Блок «Корпоративным / сертификаты» (.dop-links--vertical): список плиток-
   * ссылок, каждая = фото (imageKey S3, не URL) + ссылка + заголовок. По умолчанию
   * СКРЫТ и пуст — магазин наполняет его в админке без кода (универсально, без ниши).
   */
  corpCert: {
    enabled: boolean;
    tiles: { imageKey: string; href: string; title: string }[];
  };
}

