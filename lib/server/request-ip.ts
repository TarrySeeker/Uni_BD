import { isIP } from 'node:net';

/**
 * Определение клиентского IP из заголовков прокси — dependency-free.
 *
 * Решает ДВЕ отдельные задачи: (1) какому заголовку верить — см. «ДОВЕРИЕ
 * ИСТОЧНИКУ» ниже, это про безопасность; (2) валидность формата — ниже, это про
 * устойчивость записи в БД.
 *
 * ВАЛИДАЦИЯ ФОРМАТА (фикс major-бага reliability): IP, извлечённый из заголовков
 * `X-Forwarded-For` / `X-Real-IP`, попадает в колонки типа `inet`
 * (`sessions.ip`, `audit_log.ip`). Эти заголовки подконтрольны клиенту/прокси:
 * подделать или прислать мусор тривиально. Если записать сырую строку в `inet`,
 * Postgres падает на касте — а это ломает INSERT сессии и, как следствие, ВЕСЬ
 * вход в систему (createSession бросает на любом кривом X-Forwarded-For).
 *
 * Поэтому кандидат на IP ВАЛИДИРУЕТСЯ через `node:net` `isIP()` ДО любого
 * inet-INSERT. Невалидное значение НЕ доверяется и отбрасывается (→ undefined),
 * после чего слой БД пишет `null` (колонки `inet` nullable). Диагностический
 * IP не критичен для корректности — лучше потерять его, чем сломать логин/аудит.
 *
 * ДОВЕРИЕ ИСТОЧНИКУ (важнее валидации формата). Левый сегмент `X-Forwarded-For`
 * подконтролен клиенту: обратный прокси лишь ДОПИСЫВАЕТ свой адрес справа, а всё
 * присланное сохраняет. `X-Real-IP` наш прокси ПЕРЕЗАПИСЫВАЕТ адресом реального
 * соединения (`header_up X-Real-IP {http.request.remote.host}` в Caddyfile) —
 * подделать его снаружи нельзя. Поэтому приоритет у `X-Real-IP`.
 *
 * Чем грозил обратный порядок: IP служит ключом ограничения попыток входа и
 * пишется в журнал аудита. Доверяя `X-Forwarded-For` первым, система позволяла
 * обойти защиту от перебора паролей простой ротацией заголовка (каждый запрос —
 * «новый клиент», свежий лимит) и записать в журнал чужой адрес.
 *
 * `X-Forwarded-For` остаётся запасным вариантом: вне доверенного прокси
 * `X-Real-IP` может отсутствовать, и приблизительный диагностический адрес там
 * лучше, чем никакого. За нашим прокси до этой ветки дело не доходит.
 *
 * Функция чистая (без next/headers, БД, I/O) → тестируется в любом окружении.
 *
 * @param forwarded значение `X-Forwarded-For` (клиент-контролируемое, запасной
 *   источник; может быть списком «client, proxy1, proxy2» — берётся первый сегмент);
 * @param realIp    значение `X-Real-IP` (за прокси перезаписано реальным адресом
 *   соединения — доверенный источник, проверяется первым);
 * @returns валидный IPv4/IPv6 либо `undefined`, если ни один кандидат не валиден.
 */
export function normalizeClientIp(
  forwarded: string | null | undefined,
  realIp: string | null | undefined,
): string | undefined {
  // ПРИОРИТЕТ: X-Real-IP — его перезаписывает наш прокси, клиент влиять не может.
  const realCandidate = realIp?.trim();
  if (realCandidate && isIP(realCandidate) !== 0) {
    return realCandidate;
  }

  // Запасной вариант: X-Forwarded-For «client, proxy1, proxy2» → первый сегмент.
  // За нашим прокси сюда не попадаем: X-Real-IP задан всегда.
  const xffCandidate = forwarded?.split(',')[0]?.trim();
  if (xffCandidate && isIP(xffCandidate) !== 0) {
    return xffCandidate;
  }

  // Ни один кандидат не валиден → не доверяем мусору, отдаём undefined.
  return undefined;
}

/** Минимальный контракт источника заголовков (Headers, NextRequest.headers, мок). */
export interface HeaderSource {
  get(name: string): string | null;
}

/**
 * Клиентский IP для SERVER-TO-SERVER ВЕБХУКОВ (службы доставки, платёжные шлюзы).
 *
 * ЕДИНСТВЕННАЯ реализация — и это главное в ней. Раньше каждый роут вебхука
 * держал СВОЮ копию извлечения IP, и копии разошлись с `normalizeClientIp`:
 * в них приоритет был обратный (клиент-контролируемый `X-Forwarded-For` первым)
 * и отсутствовала валидация формата. Это тот самый класс дефекта, где защиту
 * чинят в одной функции, а трафик идёт через её двойника, — поэтому приоритет
 * источников задаётся в ОДНОМ месте выше, а точки входа зовут эту обёртку.
 *
 * Последствия старого поведения: заголовком `X-Forwarded-For: <адрес из
 * whitelist>` можно было пройти IP-фильтр вебхука, а подделанный адрес ещё и
 * сохранялся в журнале событий (отравление аудита).
 *
 * КОНТРАКТ (сохранён намеренно, от него зависит слой whitelist):
 *   • `trustProxy=false` → `''` СРАЗУ, заголовки даже не читаются: вне доверенного
 *     прокси они ничего не аутентифицируют, и непустой whitelist обязан отклонить
 *     запрос (первичная защита — секрет в query / подпись в теле);
 *   • при отсутствии доверенного кандидата возвращается `''`, а НЕ `undefined`.
 */
export function extractWebhookIp(headers: HeaderSource, trustProxy: boolean): string {
  if (!trustProxy) return '';
  return normalizeClientIp(headers.get('x-forwarded-for'), headers.get('x-real-ip')) ?? '';
}
