-- =============================================================================
-- 0062_products_display_prices.sql  (мультивалюта, этап 3: ручная «круглая» цена)
-- Карта РУЧНЫХ цен товара в валютах ОТОБРАЖЕНИЯ: {"EUR": "480.00"}.
--
-- ЗАЧЕМ. Витрина умеет показывать цены в дополнительной валюте, пересчитывая
-- рублёвую по курсу ЦБ: цена_€ = цена_₽ / rate. Арифметически верно, но на
-- ценнике премиального бренда получается «4783,12 €» вместо «480 €» — цена
-- выглядит не назначенной, а вычисленной, и меняется каждый день вслед за
-- курсом. Владелец должен иметь возможность назначить РОВНОЕ число.
--
-- 🔴 ГЛАВНОЕ ОГРАНИЧЕНИЕ: ЭТО ТОЛЬКО ПОКАЗ. base_price в базовой валюте (₽)
-- остаётся ЕДИНСТВЕННЫМ источником истины для денег — корзина, итог заказа,
-- эквайринг и возвраты считаются исключительно от него (тот же инвариант, что
-- в 0059: платёжный слой не знает ни о курсе, ни о валюте отображения).
-- Если владелец поставил «480 €» при курсе 88,76, покупатель ВИДИТ 480 € и
-- 42 605 ₽, а ПЛАТИТ 42 605 ₽. Оверрайд НЕ участвует ни в одном расчёте.
--
-- Решения:
--   * ФОРМАТ — jsonb-КАРТА «код валюты → сумма строкой», а не отдельная колонка
--     price_eur. Причина — мультитенантность: в справочнике платформы 14 валют
--     (lib/exchange/catalog.ts), у каждого магазина свой набор
--     `exchange.displayCurrencies`. Колонка на валюту потребовала бы миграции
--     под каждый новый магазин; карта масштабируется на N валют без DDL.
--     (Легаси-движок carre хранил ОДНО поле цены + флаг валюты b_work.currency
--     0=₽/1=€ — это НЕ две цены, а выбор одной; такая модель нам не подходит.)
--   * СУММЫ — СТРОКАМИ, как base_price (NUMERIC как строка): деньги через
--     double precision не гоняем, точность не теряем. Валидация формата — в
--     zod (displayPricesSchema): положительное, ≤ 2 знаков после запятой.
--   * ЕДИНИЦЫ — РУБЛИ/ЕВРО, то есть ЦЕЛЫЕ ДЕНЕЖНЫЕ ЕДИНИЦЫ, НЕ копейки/центы.
--     Копейки живут только в платёжном слое (lib/payments), куда эта колонка по
--     построению не попадает (guard-тест tests/exchange/display-prices-not-in-payments).
--   * NOT NULL DEFAULT '{}' — пустая карта означает «оверрайдов нет, считать по
--     курсу», то есть ТОЧНО ПРЕЖНЕЕ ПОВЕДЕНИЕ. Одновалютный магазин платформы
--     не заметит изменения вовсе: карта у всех товаров пустая, а форма админки
--     не покажет ни одного нового поля (полей столько, сколько доп.валют).
--     NOT NULL вместо nullable — чтобы читающий код не различал NULL и '{}'.
--   * БЕЗ CHECK-ограничения на содержимое. Валидация ключей (коды из справочника)
--     и значений — в приложении: справочник валют живёт в TypeScript и меняется
--     с релизом, зашивать его копию в CHECK значило бы держать два расходящихся
--     источника правды. БД гарантирует лишь тип jsonb и NOT NULL.
--
-- Обратная совместимость: чистое ADD COLUMN IF NOT EXISTS с DEFAULT — старый код
-- (INSERT без этой колонки, SELECT без неё) продолжает работать (§6.4, ADR-015).
-- =============================================================================

ALTER TABLE products
  ADD COLUMN IF NOT EXISTS display_prices jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN products.display_prices IS
  'Ручные цены в валютах ОТОБРАЖЕНИЯ: {"EUR":"480.00"}. ТОЛЬКО показ ценника; '
  'источник истины для денег — base_price в базовой валюте. Пусто = считать по курсу. '
  'Суммы в целых денежных единицах (рубли/евро), НЕ копейки.';

INSERT INTO schema_migrations (version, name)
VALUES ('0062', 'products_display_prices')
ON CONFLICT DO NOTHING;
