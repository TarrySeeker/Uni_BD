/**
 * Согласия субъекта персональных данных (152-ФЗ).
 *
 * КОНТЕКСТ. ФЗ-156 от 24.06.2025 изменил ч.1 ст.9 152-ФЗ: с 01.09.2025 согласие
 * на обработку ПДн оформляется ОТДЕЛЬНО от иных информации и документов. Одна
 * галочка «согласен с офертой и политикой» больше не годится — в веб-интерфейсе
 * нужен отдельный визуальный элемент под согласие на ПДн.
 *
 * Класс дефекта, ради которого механизм и появился: в боевом магазине чекаут
 * не показывал ни одной галочки, сервер поле `consent` не принимал, журнала не
 * существовало — при том что форма собирала имя, телефон и почту.
 *
 * ПОЧЕМУ ЭТО СЕРВЕРНАЯ СХЕМА, А НЕ ТОЛЬКО ГАЛОЧКА В ФОРМЕ. Проверка на клиенте
 * обходится прямым запросом к API (тот же урок, что и со stored XSS: Server
 * Action / REST-эндпоинт — это HTTP, а не «то, что прислала наша форма»).
 * Кроме того, по 152-ФЗ доказывать наличие согласия обязан оператор, поэтому
 * факт согласия не только проверяется, но и пишется в журнал (lib/consent/repository).
 *
 * Мультитенантность: виды согласий и их тексты — платформенные, ниша магазина
 * в формулировках не упоминается. Возрастного согласия здесь нет: оно нужно
 * лишь части ниш, добавляется отдельным видом и своей галочкой (таблица
 * consent_log список видов не ограничивает).
 */
import { z } from 'zod';

/** Виды согласий. Раздельные, потому что дают разный правовой эффект. */
export const CONSENT_PURPOSES = ['pd', 'offer', 'marketing'] as const;
export type ConsentPurpose = (typeof CONSENT_PURPOSES)[number];

/**
 * Версия формулировок. Меняется ВМЕСТЕ с текстами ниже: согласие оценивается по
 * редакции, действовавшей на момент его дачи, поэтому в журнал пишется и текст,
 * и версия. Формат — дата вступления редакции в силу.
 */
export const CONSENT_VERSION = '2026-08-23';

/**
 * Тексты, под которыми субъект ставит галочку. Витрина берёт подписи ОТСЮДА
 * (через /settings), а не хардкодит у себя: иначе в журнал попадёт один текст,
 * а покупатель увидит другой, и доказательная ценность журнала обнулится.
 *
 * Текст согласия на ПДн намеренно не упоминает оферту — требование
 * обособленности (ФЗ-156).
 */
export const CONSENT_TEXTS: Readonly<Record<ConsentPurpose, string>> = {
  pd: 'Я даю согласие на обработку моих персональных данных на условиях Политики обработки персональных данных.',
  offer: 'Я принимаю условия публичной оферты (договора купли-продажи).',
  marketing:
    'Я согласен получать рекламные и информационные сообщения о товарах, акциях и скидках (необязательно).',
};

/** Согласие обязательного вида: принимается ТОЛЬКО явный true. */
const requiredConsent = (message: string) => z.literal(true, { message });

/**
 * Согласия, которые витрина присылает при оформлении заказа.
 *
 * marketing — необязательное и по умолчанию false: отказ от рекламной рассылки
 * НЕ должен препятствовать покупке (ст.16 ЗоЗПП прямо запрещает обусловливать
 * приобретение товара, а ст.18 ФЗ-38 требует предварительного согласия на
 * рекламу с презумпцией вины рекламораспространителя).
 */
export const ConsentInputSchema = z.object({
  pd: requiredConsent('Необходимо согласие на обработку персональных данных.'),
  offer: requiredConsent('Необходимо принять условия оферты.'),
  marketing: z.boolean().optional().default(false),
});

export type ConsentInput = z.infer<typeof ConsentInputSchema>;

/**
 * Согласие для форм, где продажи нет (обратная связь, подписка): нужен только
 * правовой базис на обработку ПДн, оферту принимать не с чего.
 */
export const PdConsentSchema = z.literal(true, {
  message: 'Необходимо согласие на обработку персональных данных.',
});

/**
 * Раскладывает булевы флаги формы в записи журнала: одна строка на КАЖДЫЙ
 * данный вид согласия. Отказ от marketing не пишется — записывать нужно факт
 * согласия, а не его отсутствие.
 */
export function consentEntries(input: ConsentInput): ConsentPurpose[] {
  const given: ConsentPurpose[] = ['pd', 'offer'];
  if (input.marketing) given.push('marketing');
  return given;
}
