/**
 * РЕДАКТИРОВАНИЕ ПРИЧИН ОТКАЗА КОДОВ (промокод / подарочный сертификат).
 *
 * 🔴 ЗАЧЕМ (аудит, minor-безопасность — «оракул существования кодов»).
 * /cart/quote отдавал ТОЧНУЮ причину отказа кода, и по ней тривиально
 * различалось «кода нет» и «код есть»:
 *     NOSUCHCODE999  → not_found   (кода нет)
 *     SUMMER-2025    → expired     ← подтверждает: код СУЩЕСТВУЕТ
 *     erokhina_style → inactive    ← подтверждает: код СУЩЕСТВУЕТ
 * Роут публичный и дешёвый, тело запроса — корзина; это готовый оракул для
 * перебора словаря промокодов. Для сертификатов цена выше на порядок: сертификат
 * — инструмент НА ПРЕДЪЯВИТЕЛЯ (кто знает код, тот тратит деньги), и подтверждение
 * «такой код существует» сужает перебор до угадывания живого баланса.
 *
 * ОБРАЗЕЦ ПОДХОДА уже есть в проекте: маршрут заказа намеренно склеивает «заказа
 * нет» и «нет доступа» (app/api/storefront/v1/orders/[number]/route.ts), чтобы
 * перебор номеров ничего не различал. Здесь — ровно то же для кодов.
 *
 * ГДЕ РЕДАКТИРУЕМ И ПОЧЕМУ ИМЕННО ТАМ. Склейка живёт на ГРАНИЦЕ ПУБЛИЧНОГО DTO,
 * а не в домене. Домен (lib/orders/promo.ts, lib/gift-certificates) обязан
 * по-прежнему знать точную причину: она нужна логам, админке и аналитике
 * владельца («почему код не сработал»). Ослаблять домен ради приватности значило
 * бы лечить симптом не там и потерять диагностику. Наружу же уходит ОДНО
 * значение, одинаковое для «нет кода» и «код есть, но не годится».
 *
 * UX НЕ ЛОМАЕТСЯ: склеивается ПРИЧИНА, а не сообщение. Покупатель получает
 * машинный ключ, который витрина переводит в понятное «код не подошёл» на своём
 * языке (storefront/lib/checkout-errors.ts). Полезная обратная связь, которая НЕ
 * является оракулом, сохраняется отдельным значением — см. `no_amount_due`.
 *
 * Мультитенантность: правило универсально для любого магазина платформы —
 * это политика раскрытия информации, а не тексты и не ниша.
 */

/**
 * ЕДИНСТВЕННАЯ публичная причина отказа кода.
 *
 * Имя намеренно НЕ описывает состояние кода (`not_found`/`expired`/… описывали
 * бы): наружу сообщается только то, что код к этой корзине не применён.
 */
export const CODE_REJECTED_REASON = 'not_applicable';

/**
 * Причина отказа сертификата, которую редактировать НЕ надо.
 *
 * `no_amount_due` — про состояние КОРЗИНЫ («покрывать нечего, к оплате уже 0»),
 * а не про существование кода. Оракулом он не является: до него доходит лишь
 * владелец ВАЛИДНОГО кода. Схлопнув и его, мы сломали бы полезную обратную связь
 * — покупатель считал бы рабочий сертификат негодным и пробовал снова.
 */
const GIFT_CART_STATE_REASONS: ReadonlySet<string> = new Set(['no_amount_due']);

/**
 * Причина отказа ПРОМОКОДА → публичное значение.
 *
 * Склеивает ВСЁ (fail-closed: неизвестное/новое доменное значение тоже
 * склеивается — иначе будущая причина протекла бы наружу молча). `null`/`undefined`
 * (код применён) остаётся `null`: успех редактировать нечего и незачем.
 */
export function publicPromoReason(reason: string | null | undefined): string | null {
  if (reason == null) return null;
  return CODE_REJECTED_REASON;
}

/**
 * Причина отказа СЕРТИФИКАТА → публичное значение.
 *
 * Всё, что говорит о СУЩЕСТВОВАНИИ кода (not_found/expired/depleted/disabled/…),
 * склеивается в одно значение; причины про состояние корзины проходят как есть.
 */
export function publicGiftReason(reason: string | null | undefined): string | null {
  if (reason == null) return null;
  if (GIFT_CART_STATE_REASONS.has(reason)) return reason;
  return CODE_REJECTED_REASON;
}
