/**
 * Проверка СУЩЕСТВОВАНИЯ пункта выдачи (ПВЗ/постамата) перед созданием заказа.
 *
 * 🔴 ЗАЧЕМ (аудит, major — «заказ, который невозможно отгрузить»).
 * `pvzCode` проходил только ФОРМАЛЬНУЮ валидацию схемы («непустая строка ≤64»,
 * deliverySelectionSchema) и напрямую попадал в `orders.delivery_pvz_code`, а
 * оттуда — в СДЭК как `delivery_point` (lib/cdek/services/order). Существование
 * пункта не проверял НИКТО. На боевых ключах последствие деньгами: заказ
 * создаётся, покупатель ПЛАТИТ, а накладную по нему не создать никогда — СДЭК
 * отвергает неизвестный ПВЗ, крон создания отправлений падает бесконечно, заказ
 * повисает. Это ровно тот же класс, что закрытые major №3/№18.
 *
 * АСИММЕТРИЯ, которую здесь устраняем: неизвестный `zoneId` отбивался ЖЁСТКО
 * (resolveDeliveryZoneStrict → UnknownDeliveryZoneError → `invalid_zone`), а
 * неизвестный `pvzCode` — нет. Приводим ПВЗ к той же строгости.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ FAIL-OPEN ПРИ НЕДОСТУПНОСТИ СЛУЖБЫ (ключевое решение)
 *
 * Проверка ПВЗ — единственная в чекауте, которая требует СЕТЕВОГО обращения к
 * внешней службе просто чтобы сказать «да/нет». Отсюда два принципиально разных
 * исхода, которые нельзя схлопывать:
 *
 *   1) СДЭК ОТВЕТИЛ и сказал «такого пункта нет» (findOffice → null). Это
 *      ЗНАНИЕ. Заказ отгрузить нельзя — отказываем жёстко (`invalid_pvz`).
 *
 *   2) СДЭК НЕ ОТВЕТИЛ (сеть, 5xx, таймаут, протухшие ключи). Это ОТСУТСТВИЕ
 *      знания, а не «код плохой». Трактовать его как отказ — значит превратить
 *      любой сбой внешнего API в полную остановку продаж магазина: ни один
 *      заказ с доставкой в ПВЗ не оформится, пока СДЭК лежит. Цена ошибки
 *      несимметрична: ложный отказ бьёт по ВСЕМ заказам сразу и прямо сейчас,
 *      ложный пропуск — по одному заказу, который к тому же ловится позже
 *      (крон создания накладной + владелец в админке видит ошибку отправления).
 *      Поэтому недоступность службы → ПРОПУСКАЕМ (fail-open).
 *
 * ЭТО НЕ ПРОТИВОРЕЧИТ anti-undercharge-политике доставки (там сбой расчёта
 * БРОСАЕТ, DeliveryCalculationError): там на кону ДЕНЬГИ — без ответа службы
 * стоимость неизвестна, и тихий 0.00 = недоплата магазину. Здесь денег нет:
 * стоимость уже посчитана отдельно, а «код ПВЗ, возможно, верен» деньгами
 * магазину не грозит. Разная цена ошибки — разная политика.
 *
 * Заметим: заказ с недоступным СДЭК всё равно не пройдёт дальше, если СДЭК был
 * нужен для РАСЧЁТА (computeDeliveryCost бросит первым) — fail-open здесь не
 * открывает новую дыру, а лишь не добавляет второй точки отказа.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * MOCK-РЕЖИМ. При пустых CDEK_* менеджер СДЭК работает на фикстурах
 * (MSK1/MSK2/MSK-POST1 + синтетические MOCK-<cityCode>), и findOffice даёт по
 * ним честные да/нет — проверка полноценно работает и на стенде, и на боевых
 * ключах, одним и тем же кодом.
 *
 * РАЗВЯЗКА orders↔cdek. Как и в delivery-cost.ts: НЕТ статического импорта
 * `@/lib/cdek` — модуль опционален и может быть выключен на деплое. cdek
 * подтягивается ленивым динамическим import-ом и только когда проверка
 * применима. Мультитенантность: ни одного допущения о конкретном магазине.
 */

import { isModuleEffectivelyEnabled } from '@/lib/config/settings';
import type { DeliveryType } from './types';

/**
 * Исход проверки ПВЗ.
 *   • found       — служба подтвердила существование пункта;
 *   • not_found   — служба ОТВЕТИЛА, что такого пункта нет (жёсткий отказ);
 *   • unavailable — службу не удалось спросить (сеть/конфиг) — знания нет;
 *   • skipped     — проверять нечего/нечем (не ПВЗ-доставка, нет кода, cdek off).
 */
export type PvzVerificationOutcome = 'found' | 'not_found' | 'unavailable' | 'skipped';

/** Результат проверки. Отдельным объектом — чтобы дальше добавлять поля аддитивно. */
export interface PvzVerificationResult {
  outcome: PvzVerificationOutcome;
}

/** Решение по результату проверки: пропустить заказ или отказать. */
export type PvzVerificationDecision = 'ok' | 'reject';

/**
 * ЧИСТОЕ решение по исходу проверки — вся политика fail-open собрана ЗДЕСЬ,
 * в одном тестируемом месте, чтобы её нельзя было случайно «переизобрести» в
 * вызывающем коде. Отказ ровно один: служба ответила «пункта нет».
 */
export function classifyPvzVerification(result: PvzVerificationResult): PvzVerificationDecision {
  return result.outcome === 'not_found' ? 'reject' : 'ok';
}

/** Вход проверки: тип доставки заказа и присланный покупателем код пункта. */
export interface VerifyPvzInput {
  deliveryType: DeliveryType | undefined;
  pvzCode?: string | null;
}

/**
 * Спрашивает у СДЭК, существует ли пункт выдачи с таким кодом.
 *
 * Не бросает НИКОГДА: любая ошибка транспорта превращается в `unavailable`
 * (см. политику в шапке модуля). Вызывающий обязан прогнать результат через
 * classifyPvzVerification, а не разбирать outcome вручную.
 */
export async function verifyPvzCode(input: VerifyPvzInput): Promise<PvzVerificationResult> {
  const code = (input.pvzCode ?? '').trim();
  // Проверять нечего: доставка не в пункт выдачи либо код не прислан.
  // Обязательность самого кода для type='pvz' — забота схемы (superRefine).
  if (code === '' || input.deliveryType !== 'pvz') {
    return { outcome: 'skipped' };
  }

  // Модуль cdek выключен → магазин возит сам и справочника ПВЗ не имеет.
  // Спросить некого, а значит и отказывать не за что (та же логика, что у
  // stub-провайдера доставки при выключенном cdek).
  if (!(await isModuleEffectivelyEnabled('cdek'))) {
    return { outcome: 'skipped' };
  }

  try {
    // Ленивый импорт — статической связки orders→cdek нет (см. delivery-cost.ts).
    const [{ PvzService }, { getCdekManager }] = await Promise.all([
      import('@/lib/cdek/services/pvz'),
      import('@/lib/cdek/manager'),
    ]);
    // Метод УЖЕ существовал (lib/cdek/services/pvz.ts) и до этой правки
    // использовался только листингом ПВЗ на витрине — на пути заказа его не звал
    // никто. Здесь он и закрывает дефект.
    const office = await new PvzService(getCdekManager()).findOffice(code);
    return { outcome: office ? 'found' : 'not_found' };
  } catch {
    // Сеть/конфиг/протухшие ключи — знания нет. НЕ выдаём это за «код неверный»:
    // иначе сбой СДЭК блокирует все заказы магазина (см. шапку модуля).
    return { outcome: 'unavailable' };
  }
}
