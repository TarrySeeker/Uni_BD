-- =============================================================================
-- 0040_atol_payments.sql — модуль payments/atol (АТОЛ Pay Ecom)
-- Журнал событий эквайринга АТОЛ + допуск провайдера atol на заказе.
--
-- Решение (порт 0038_ozon_payments, который сам был портом 0027_tbank_payments):
--   * atol_payment_log — лог входящих callback с ключом идемпотентности, чтобы
--     повторная доставка вебхука не применяла переход дважды;
--   * orders.payment_provider — расширяем CHECK значением atol. БЕЗ ЭТОГО любая
--     запись провайдера atol отвергалась бы ограничением из 0038 (там разрешены
--     tbank, ozon и manual) — заказ терял бы связь с платежом.
--
-- ЧЕМ АТОЛ ОТЛИЧАЕТСЯ ОТ ДВУХ ПРЕДЫДУЩИХ ЭКВАЙЕРОВ (и почему схема не копия):
--   1. НЕТ transactionUid. У Т-Банка попытка опознаётся PaymentId, у Озона —
--      transactionUid (UUID). У АТОЛа сквозного идентификатора попытки нет
--      вообще: в callback приходит только НАШ orderId. Ключ идемпотентности
--      пришлось строить из содержания события — см. блок «КЛЮЧ ИДЕМПОТЕНТНОСТИ».
--   2. ОДИН URL НА ВСЕ СОБЫТИЯ. Тип различается полем `type`
--      (payment | deposit | cancel | refund | fiscal), поэтому `type` — часть
--      ключа, а не справочная колонка.
--   3. errorCode ТЕКСТОВЫЙ (AUTH_ERROR, INVALID_RECEIPT_AMOUNT, …), а не
--      числовой как у Озона. Колонка text, не integer: integer тут молча
--      обрежет диагностику до NULL при вставке.
--   4. У CALLBACK НЕТ ПОДПИСИ. Ни HMAC, ни секрета, ни контрольной суммы. Тело
--      само по себе НЕ доказывает отправителя, поэтому запись в этот журнал —
--      это протокол «что нам прислали», а НЕ основание менять статус заказа.
--      Решение о смене статуса код принимает по ответу
--      GET /payments/{orderId}/status, запрошенному нами по токену.
--      Практическое следствие для схемы: в журнал могут попадать события,
--      которые АТОЛ не отправлял, — поэтому processed остаётся отдельным
--      флагом «переход применён», а не выводится из наличия строки.
--
-- КЛЮЧ ИДЕМПОТЕНТНОСТИ: (atol_order_id, type, payment_status, receipt_type).
--   Почему так. Единственное, что АТОЛ присылает стабильно во всех событиях, —
--   orderId (наш идентификатор заказа, он же ключ платежа на стороне АТОЛа:
--   повторная регистрация того же orderId отбивается кодом PAYMENT_EXISTS, то
--   есть orderId ↔ платёж соотносятся один к одному). Одного orderId мало:
--   по одному платежу законно приходит НЕСКОЛЬКО разных событий (payment →
--   fiscal → refund). Добавляем `type` — но и его мало: событие `payment`
--   приходит на каждую смену paymentStatus (0 «в обработке» → 10 «подтверждение
--   3DS» → 1 «успех»), и это РАЗНЫЕ события, схлопывать их нельзя — иначе
--   журнал потеряет факт оплаты, оставив в себе только первое «в обработке».
--   Отсюда (заказ, тип события, числовой статус): одно и то же событие — ровно
--   один раз, а легальная последовательность переходов сохраняется целиком. Это
--   тот же принцип, что (transaction_uid, status) у Озона, просто роль
--   идентификатора попытки играет orderId.
--
--   🔴 ЧЕТВЁРТЫЙ ЧЛЕН — receipt_type — И ПОЧЕМУ БЕЗ НЕГО КЛЮЧ БЫЛ НЕВЕРЕН.
--   У события `fiscal` числового статуса нет, значит COALESCE(payment_status,-1)
--   даёт -1 ВСЕГДА и тройка вырождалась бы в (orderId, 'fiscal', -1) — ровно
--   ОДИН слот на заказ. А чеков по одному заказу законно бывает ДВА:
--   receiptType 'sell' (приход при оплате) и 'sell_refund' (возврат прихода при
--   возврате денег). Второй схлопнулся бы с первым и был бы молча отброшен как
--   дубль. Цена ошибки — не «потеря строки в журнале»: если возвратный чек НЕ
--   ПРОБИЛСЯ, флаг receipt_failed не выставился бы, и ровно тот сценарий, ради
--   которого этот флаг заведён (нарушение 54-ФЗ, чек коррекции в срок), стал бы
--   НЕВИДИМ. Хуже того, неудачный `fiscal` при оплате занял бы единственный слот
--   и вытеснил бы последующий чек по возврату. Поэтому receipt_type входит в
--   ключ: (o,'fiscal',-1,'sell') и (o,'fiscal',-1,'sell_refund') — разные строки,
--   а ретрай одного и того же чека по-прежнему отбивается. Для НЕфискальных
--   событий receipt_type пуст, свёрнут тем же COALESCE в '' и на них не влияет.
--
--   ПОЧЕМУ В КЛЮЧЕ НЕТ receipt_id (сознательный отказ). Соблазн очевиден: у
--   разных чеков разные receiptId, и они тоже различали бы события. Но receiptId
--   генерируется НА СТОРОНЕ АТОЛА и уникален сам по себе — включив его, мы
--   сделали бы РАЗЛИЧНЫМ каждый ретрай, если АТОЛ хоть раз пришлёт тот же чек с
--   новым идентификатором, и уникальный индекс перестал бы защищать от повторной
--   доставки — то есть от единственного, ради чего он существует. receipt_type —
--   наоборот, ЗАКРЫТЫЙ домен из двух значений (закреплён CHECK ниже): он
--   различает ровно два законных чека и не добавляет ключу ни одной лишней
--   степени свободы. Общее правило: чем больше членов в ключе, тем слабее защита
--   от ретраев, поэтому добавляем только то, что различает СМЫСЛ события, а не
--   его экземпляр.
--
--   🔴 ГРАНИЦА ПРИМЕНИМОСТИ, о которой обязан знать тот, кто пишет обработчик.
--   Ключ отсекает ПОВТОРНУЮ ДОСТАВКУ одного события (ретрай вебхука) — ровно то,
--   ради чего он нужен. Он НЕ различает два содержательно разных события, у
--   которых совпали все четыре члена: например два ЧАСТИЧНЫХ возврата по одному
--   заказу на разные суммы оба дадут (orderId, 'refund', 8, '') и второй будет
--   отброшен как дубль. Это осознанный остаток: различающего идентификатора у
--   такой пары в теле callback нет вовсе (в отличие от пары чеков, которую
--   различает receipt_type, — потому она и починена). Поэтому СУММА возврата
--   берётся не из журнала, а сверкой с GET /payments/{orderId}/status, а
--   частичные возвраты проводятся через админку, которая знает собственную
--   историю списаний.
--
--   🔴 ТЕХНИЧЕСКАЯ ЛОВУШКА NULL В УНИКАЛЬНОМ ИНДЕКСЕ. payment_status nullable —
--   в событии `fiscal` его нет. В Postgres NULL-ы в уникальном индексе
--   считаются РАЗЛИЧНЫМИ, поэтому наивный UNIQUE (atol_order_id, type,
--   payment_status) НЕ защитил бы как раз события фискализации: каждый ретрай
--   лёг бы новой строкой. Поэтому в индексе NULL свёрнут в -1 через COALESCE
--   (-1 недостижим: статусы АТОЛа 0..12, неотрицательность закреплена CHECK
--   ниже). Тот же приём уже применён в ките — 0008, 0010, 0024.
--   Альтернатива NULLS NOT DISTINCT намеренно не взята: она появилась только в
--   Postgres 15 и связала бы кит с версией, тогда как COALESCE работает везде.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Расширяем допустимые значения orders.payment_provider значением atol.
--
-- check-migrations: allow drop-constraint (CHECK нельзя расширить, не пересоздав:
--   два CHECK на колонке действуют по «И», старый отверг бы нового провайдера)
-- ВНИМАНИЕ: ОСОЗНАННОЕ ОТСТУПЛЕНИЕ от правила аддитивности — здесь
-- scripts/check-migrations.sh справедливо ловит DROP CONSTRAINT.
-- Обоснование (то же, что в 0027 и 0038; воспроизводится при каждом новом
-- эквайере — это штатный, а не разовый приём расширения перечня провайдеров):
--   * CHECK нельзя РАСШИРИТЬ, не пересоздав: два CHECK на одной колонке действуют
--     по «И», поэтому добавление второго (с atol) не помогает — старый всё равно
--     отвергнет значение;
--   * правило защищает от снятия инварианта, на который опирается СТАРЫЙ код.
--     Здесь инвариант не снимается, а РАСШИРЯЕТСЯ: перечень допустимых провайдеров
--     дополняется значением, которое пишет только новый код. Все ранее допустимые
--     значения (tbank, ozon, manual) остаются допустимыми — старый код не ломается
--     ни на чтении, ни на записи;
--   * снятие и установка идут в ОДНОЙ транзакции (DO-блок) — окна, в котором
--     таблица осталась бы без ограничения, не возникает. Параллельная транзакция
--     либо ждёт блокировки, либо видит уже новое ограничение; состояния «провайдер
--     не проверяется» не существует ни мгновения;
--   * ограничение помечено NOT VALID: существующие строки повторно не проверяются.
--     Это важно не только ради скорости — к моменту наката 0040 в таблице УЖЕ есть
--     боевые заказы с payment_provider (в отличие от 0038, где их не было). Полная
--     валидация взяла бы долгую блокировку на orders на ровном месте; новые и
--     изменяемые строки ограничением проверяются в любом случае, а старые заведомо
--     содержат значения из прежнего, более узкого перечня — то есть допустимые.
-- Откат: вернуть перечень ('tbank','ozon','manual') тем же приёмом.
-- Запуск линтера по этому файлу ожидаемо даёт предупреждение об отступлении.
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_payment_provider_chk') THEN
    ALTER TABLE orders DROP CONSTRAINT orders_payment_provider_chk;
  END IF;

  ALTER TABLE orders
    ADD CONSTRAINT orders_payment_provider_chk
    CHECK (payment_provider IS NULL OR payment_provider IN ('tbank', 'ozon', 'atol', 'manual'))
    NOT VALID;
END $$;

-- -----------------------------------------------------------------------------
-- atol_payment_log — лог входящих callback АТОЛа.
--
-- raw_payload храним ЦЕЛИКОМ, в отличие от Озона (там вырезается requestSign).
-- Вырезать нечего: секрета в теле нет — он приходит query-параметром в URL и в
-- тело не попадает. 🔴 Тот, кто будет логировать сам URL вебхука (прокси, access
-- log, отладочная печать), обязан помнить, что секрет лежит именно там: URL с
-- секретом в логе = скомпрометированный канал аутентификации вебхука.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS atol_payment_log (
  id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id         uuid        NOT NULL,                   -- FK → orders.id (ниже)
  atol_order_id    text        NOT NULL,                   -- orderId: наш id заказа, он же ключ платежа у АТОЛа
  type             text        NOT NULL                    -- тип события: один URL на все
                   CHECK (type IN ('payment', 'deposit', 'cancel', 'refund', 'fiscal')),

  -- 🔴 ЧИСЛОВОЙ статус платежа (0..12) — ЕДИНСТВЕННЫЙ достоверный источник факта
  -- оплаты. Поле `status` того же тела («success» | «fail» | «error») — это статус
  -- ОБРАБОТКИ ЗАПРОСА: в примере документации status «success» соседствует с
  -- paymentStatus 0 («в обработке»). Трактовать `status` как оплату = отдать товар
  -- за неоплаченный заказ, поэтому в отдельную колонку вынесен именно paymentStatus.
  -- NULL допустим: в событии `fiscal` числового статуса платежа нет.
  payment_status   smallint    CHECK (payment_status IS NULL OR payment_status BETWEEN 0 AND 12),

  -- Статус обработки запроса как прислан, для аудита. Решения по нему не принимаем
  -- НИКОГДА, кроме одного случая — события `fiscal`, см. receipt_failed ниже.
  request_status   text,

  amount_kop       bigint      CHECK (amount_kop IS NULL OR amount_kop >= 0),  -- сумма события, КОПЕЙКИ (10000 = 100 ₽)

  -- Событие фискализации (type = 'fiscal').
  receipt_id       text,                                   -- receiptId выданного чека
  receipt_type     text                                    -- sell (приход) | sell_refund (возврат прихода)
                   CHECK (receipt_type IS NULL OR receipt_type IN ('sell', 'sell_refund')),

  -- ───────────────────────────────────────────────────────────────────────────
  -- 🔴 НЕПРОБИТЫЙ ЧЕК — САМОЕ ОПАСНОЕ СОБЫТИЕ ВО ВСЁМ ЭТОМ ЖУРНАЛЕ.
  --
  -- Документация АТОЛа прямо предупреждает: «транзакция не отменяется, если чек
  -- отправился неуспешно». То есть событие type='fiscal' со status='fail'
  -- означает: ДЕНЬГИ С ПОКУПАТЕЛЯ СПИСАНЫ, А ЧЕК НЕ ПРОБИТ. Это нарушение 54-ФЗ,
  -- и чинится оно только вручную (чек коррекции), причём в срок.
  --
  -- Почему отдельная КОЛОНКА, а не вычисление на лету. Такое событие обязано быть
  -- видно оператору, а не «выводимо запросом, если кто-то догадается его написать».
  -- Признак «чек не пробит» лежал бы иначе в трёх местах сразу (type, request_status,
  -- error_code) — любой обработчик, забывший одно из условий, молча потеряет
  -- нарушение закона. Отдельный булев флаг:
  --   * даёт дешёвый partial-индекс ix_atol_payment_log_receipt_failed — лист
  --     непробитых чеков открывается одним запросом без скана журнала;
  --   * даёт алерту и админке ОДНО условие (receipt_failed AND NOT processed),
  --     которое нельзя недосмотреть;
  --   * переживает смену словарей АТОЛа: изменится набор кодов ошибок — правится
  --     код, который выставляет флаг, а не все читатели журнала.
  -- Флаг выставляет обработчик callback; processed по такому событию НЕ ставится,
  -- пока оператор не разберёт его, — непробитый чек не «обработан» фактом записи
  -- в журнал.
  -- ⚠️ Флаг сам по себе НЕ поднимает тревогу: алерт (письмо/пометка в админке)
  -- вешается кодом на этот индекс. Колонка без алерта — это по-прежнему
  -- нарушение, просто аккуратно записанное.
  -- ───────────────────────────────────────────────────────────────────────────
  receipt_failed   boolean     NOT NULL DEFAULT false,

  -- 🔴 ТЕКСТОВЫЙ код ошибки (AUTH_ERROR, PAYMENT_EXISTS, INVALID_RECEIPT_AMOUNT,
  -- PAYMENT_NOT_FOUND …) — в отличие от числового errorCode Озона.
  error_code       text,
  error_message    text,

  is_mock          boolean     NOT NULL DEFAULT false,     -- событие локального mock-режима (боевой токен не задан)
  raw_payload      jsonb,                                  -- тело callback целиком (аудит и разбор инцидентов)
  processed        boolean     NOT NULL DEFAULT false,     -- применён ли переход payment_status заказа
  ip               text,                                   -- отправитель: подписи нет, происхождение восстанавливается только так
  received_at      timestamptz NOT NULL DEFAULT now()
);

-- Ключ идемпотентности: одно событие (заказ + тип + числовой статус + тип чека) —
-- ровно один раз.
--   * COALESCE(payment_status, -1) закрывает `fiscal`, где статуса нет: без него
--     NULL-ы считались бы РАЗЛИЧНЫМИ и каждый ретрай ложился бы новой строкой;
--   * COALESCE(receipt_type, '') различает два законных чека одного заказа —
--     'sell' (приход) и 'sell_refund' (возврат прихода). Без этого члена оба
--     схлопывались бы в единственный слот (orderId,'fiscal',-1), и непробитый
--     ВОЗВРАТНЫЙ чек не попал бы в журнал вообще — то есть нарушение 54-ФЗ стало
--     бы невидимым. На нефискальные события не влияет: там receipt_type пуст.
-- Полное обоснование, отказ от receipt_id и граница применимости — в шапке файла.
CREATE UNIQUE INDEX IF NOT EXISTS uq_atol_payment_log_idem
  ON atol_payment_log (atol_order_id, type, COALESCE(payment_status, -1), COALESCE(receipt_type, ''));
CREATE INDEX IF NOT EXISTS ix_atol_payment_log_order ON atol_payment_log (order_id);
CREATE INDEX IF NOT EXISTS ix_atol_payment_log_atol  ON atol_payment_log (atol_order_id);

-- Разбор непробитых чеков: partial-индекс, а не полный — строк с флагом должно
-- быть исчезающе мало, и именно их ищут срочно (54-ФЗ, чек коррекции в срок).
CREATE INDEX IF NOT EXISTS ix_atol_payment_log_receipt_failed
  ON atol_payment_log (received_at DESC)
  WHERE receipt_failed;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'atol_payment_log_order_fk') THEN
    ALTER TABLE atol_payment_log
      ADD CONSTRAINT atol_payment_log_order_fk
      FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE;
  END IF;
END $$;

