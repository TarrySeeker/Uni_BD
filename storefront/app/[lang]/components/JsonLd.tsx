/**
 * Вставка JSON-LD-разметки в разметку страницы (`<script type="application/ld+json">`).
 *
 * 🔴 БЕЗОПАСНОСТЬ. Внутрь попадают данные магазина (заголовки страниц из админки),
 * то есть значения, которые редактирует человек. Внутри `<script>` браузер НЕ
 * декодирует HTML-сущности, поэтому единственный реальный вектор — литерал
 * `</script>` в строке: он закрыл бы тег и всё, что дальше, стало бы разметкой.
 * Экранируем `<` как `<` — JSON остаётся валидным (это законная escape-
 * последовательность JSON-строки), а последовательность `</script>` больше не
 * встречается. Заодно экранируем U+2028/U+2029 (в JSON легальны, но в JS
 * считаются переводом строки и ломают старые парсеры).
 */

export default function JsonLd({ data }: { data: unknown }) {
  if (data == null) return null;

  const json = JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');

  return (
    <script
      type="application/ld+json"
      // Значение уже экранировано выше; иначе React вставил бы строку как текст
      // узла и разметка не была бы прочитана поисковиком.
      dangerouslySetInnerHTML={{ __html: json }}
    />
  );
}
