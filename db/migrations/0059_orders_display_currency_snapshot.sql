-- =============================================================================
-- 0059_orders_display_currency_snapshot.sql  (мультивалюта: что ВИДЕЛ покупатель)
-- Снимок ВАЛЮТЫ ОТОБРАЖЕНИЯ и курса на момент оформления заказа.
--
-- ЗАЧЕМ (денежный риск, разбор претензий). Витрина умеет показывать цены в
-- ДОПОЛНИТЕЛЬНОЙ валюте (переключатель ₽/€ в шапке, курс ЦБ РФ обновляется
-- кроном), а эквайринг у магазина РУБЛЁВЫЙ: списывается `orders.grand_total` в
-- базовой валюте. Покупатель, ходивший по каталогу в евро, платит рублями.
-- Дисклеймер на чекауте теперь называет обе суммы, но САМ ФАКТ («клиент видел
-- 480 €, курс был 88,76») нигде не сохранялся: курс меняется ежедневно, и через
-- неделю по спорному заказу восстановить, что именно было на экране, НЕЛЬЗЯ.
-- Отсюда — три справочных поля-снимка.
--
-- Решения:
--   * ВСЕ ТРИ NULL-able БЕЗ DEFAULT. NULL = «заказ оформлен в БАЗОВОЙ валюте»
--     (переключатель не трогали) либо «заказ старше этой миграции». Это ЧЕСТНОЕ
--     «неизвестно/не применимо», а не выдуманный курс 1.0. Одновалютный магазин
--     платформы не увидит изменений вовсе: поля всегда NULL.
--   * ЗАПОЛНЯЮТСЯ ТОЛЬКО СЕРВЕРОМ (ADR-010 anti-tamper). Клиент присылает лишь
--     КОД валюты отображения, которую выбрал; курс сервер берёт из настроек
--     магазина (shop_settings.exchange), а display_total считает САМ от своего
--     рублёвого итога. Клиентское число к деньгам не допускается ни в каком виде.
--   * НЕ УЧАСТВУЮТ В РАСЧЁТАХ. grand_total, платёжный путь, сверка с эквайером и
--     возвраты от этих полей не зависят вообще — они справочные. Именно поэтому
--     колонки добавляются, а не переопределяются существующие суммы.
--   * ЕДИНИЦЫ. display_total — ДЕНЬГИ В ВАЛЮТЕ ОТОБРАЖЕНИЯ (евро), numeric(14,2),
--     ровно как остальные суммы заказа: рубли/евро, НЕ копейки (копейки живут
--     только в платёжном слое, lib/payments). display_rate — единиц БАЗОВОЙ
--     валюты за 1 единицу валюты отображения (EUR rate=88.7602 → 1 € = 88,7602 ₽,
--     значит цена_€ = цена_₽ / rate). numeric(18,8): курсы ЦБ публикуются с 4
--     знаками, но валюты с крупным номиналом (за 100/1000 единиц) и будущие
--     ручные курсы требуют запаса — 8 знаков закрывают их без потери точности.
--   * ОКРУГЛЕНИЕ. display_total считается ОТ РУБЛЁВОГО ИТОГА (grand_total / rate),
--     а НЕ суммированием округлённых позиций: второй способ расходится с итогом
--     на единицы валюты и порождает ровно ту претензию, ради которой снимок и
--     делается.
--   * display_currency — БЕЗ FK и без CHECK на список валют: настройки магазина
--     меняются (валюту отображения можно убрать), а снимок обязан пережить это
--     как исторический факт. Текст, как и orders.currency.
--   * GRANT: права в 0012 выданы НА ТАБЛИЦУ orders целиком, табличная привилегия
--     PostgreSQL распространяется на добавленные позже колонки.
--
-- Идемпотентно и АДДИТИВНО (проходит scripts/check-migrations.sh):
--   ADD COLUMN IF NOT EXISTS; schema_migrations — ON CONFLICT DO NOTHING.
--   НЕТ DROP/RENAME/смены типа/SET NOT NULL.
-- =============================================================================

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS display_currency text,
  ADD COLUMN IF NOT EXISTS display_rate     numeric(18,8),
  ADD COLUMN IF NOT EXISTS display_total    numeric(14,2);

COMMENT ON COLUMN orders.display_currency IS 'Валюта ОТОБРАЖЕНИЯ, выбранная покупателем на витрине (ISO-4217); NULL — заказ оформлен в базовой валюте';
COMMENT ON COLUMN orders.display_rate IS 'Курс на момент заказа: единиц базовой валюты за 1 единицу валюты отображения (цена_отобр = цена_базовая / rate); NULL — без валюты отображения';
COMMENT ON COLUMN orders.display_total IS 'Итог заказа в валюте отображения (справочно, = grand_total / display_rate); деньги, НЕ копейки; NULL — без валюты отображения';

INSERT INTO schema_migrations (version, name)
VALUES ('0059', 'orders_display_currency_snapshot')
ON CONFLICT DO NOTHING;
