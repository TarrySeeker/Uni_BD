  /** Не хватило остатка под резерв (единственная причина 409). */
  'out_of_stock',
  /** Позиция корзины недоступна (нет товара/варианта/снята с продажи). */
  'invalid_item',
  /** Промокод отклонён (не найден/истёк/лимит/минимум). */
  'invalid_promo',
  /** Подарочный сертификат отклонён (не найден/истёк/исчерпан/гонка баланса). */
  'invalid_gift',
  /** Требуемый расчёт доставки не удался (сеть/отказ службы). */
  'delivery_unavailable',
  /** Прислана зона доставки, которой нет в настройках магазина. */
  'invalid_zone',
  /**
   * Прислан код пункта выдачи, которого нет в справочнике службы доставки.
   * Отдельная причина, а не `delivery_unavailable`: покупателю нужно ВЫБРАТЬ
   * пункт заново (адрес/способ менять не надо), и это его единственное действие.
   */
  'invalid_pvz',
  /** Выбран онлайн-способ оплаты при выключенном модуле payments. */
  'payments_disabled',
  /** Заказ не найден / токен доступа не подошёл (инициация оплаты). */
  'order_not_found',
  /** Заказ уже оплачен, возвращён или закрыт — платить нечего. */
  'order_not_payable',
  /** Платёжный шлюз не принял инициацию (сеть/отказ провайдера). */
  'payment_init_failed',
  /**
   * Оплата по заказу УЖЕ ИДЁТ: деньги удержаны на карте (холд), ждём
   * подтверждения. Отдельная причина, а не `order_not_payable`: покупателю здесь
   * нужен принципиально другой текст — «повторять не надо, деньги не потеряны»,
   * а не «этот заказ оплатить нельзя».
   */
  'payment_in_progress',
  /**
   * Итог, показанный покупателю, НЕ СОВПАЛ с фактическим итогом заказа
   * (аудит 2026-07-26, находки №2 и №9). Клиент прислал `expectedGrandTotal`,
   * сервер пересчитал сумму заново и получил другое значение: состав/цены/остаток
   * сертификата изменились между расчётом и оформлением, либо повторный submit
   * пришёл с прежним Idempotency-Key после смены состава и переиспользовал заказ
   * со старыми суммами. Отказ ВМЕСТО тихого создания/выдачи заказа: покупатель не
   * должен уходить на шлюз платить сумму, которой не видел.
   */
  'total_mismatch',
