-- 0050_product_colors.sql  (порт легаси-блока carre `.wv__colors` на витрину)
-- -----------------------------------------------------------------------------
-- ДИСПЛЕЙНЫЕ цвето-свотчи товара (кружочки на карточке) — НЕ покупаемые
-- варианты/SKU. Источник на старом carrerusse.com: b_work.color_hex/master_color
-- (+ второй цвет color_hex_2/master_color_2). Здесь это чисто презентационные
-- данные товара, поэтому храним их как JSONB-массив на самом товаре — зеркально
-- attributes_cache (ADR-007: JSONB-проекция презентационных данных поверх/рядом с
-- каталогом), а НЕ через product_variants/product_attributes (это не варианты и
-- не фасетные атрибуты — товар с двумя свотчами остаётся одним SKU).
--
-- Формат значения (валидируется на write-path Zod-схемой, см. lib/catalog):
--   colors = [ { "hex": "#RRGGBB", "name": "Красный" }, ... ]
--   • hex  — строка вида '#rrggbb' (нижний регистр не обязателен), рендерится как
--            background кружка `.wv__color`;
--   • name — русское имя из словаря b_master_colors (title кружка); может быть ''.
-- Порядок массива = порядок отображения (первый = основной цвет, второй = _2).
--
-- Строго АДДИТИВНО (check-migrations.sh): ADD COLUMN IF NOT EXISTS с NOT NULL
-- DEFAULT '[]'::jsonb — старый код не знает про колонку, существующие товары
-- получают пустой массив (блок свотчей не рендерится). Обратно совместимо.
--
-- Мультитенантность: без tenant_id (ADR-003: 1 магазин = 1 БД).
-- Идемпотентно: ADD COLUMN IF NOT EXISTS; запись в schema_migrations
-- ON CONFLICT DO NOTHING. Табличный GRANT (0006) автоматически покрывает новую
-- колонку — отдельный GRANT не нужен.
-- =============================================================================

-- Дисплейные цвето-свотчи товара: JSONB-массив [{hex,name}]. Пустой массив →
-- у товара нет цветов, блок `.wv__colors` на витрине не рендерится.
ALTER TABLE products
  ADD COLUMN IF NOT EXISTS colors jsonb NOT NULL DEFAULT '[]'::jsonb;

INSERT INTO schema_migrations (version, name)
VALUES ('0050', 'product_colors')
ON CONFLICT DO NOTHING;
