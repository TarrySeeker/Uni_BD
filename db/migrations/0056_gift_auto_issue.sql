-- -----------------------------------------------------------------------------
-- Выборка «оплаченные заказы за последнее окно» (страховочный проход, который
-- доподготавливает коды по заказам, где выпуск не случился в момент оплаты).
-- Существующий orders_payment_idx (payment_status) для неё почти бесполезен:
-- по мере роста магазина ПОДАВЛЯЮЩЕЕ большинство заказов имеет статус 'paid',
-- и планировщику всё равно пришлось бы сортировать их по paid_at. Частичный
-- индекс по paid_at внутри оплаченных даёт прямой диапазонный доступ и не растёт
-- за счёт неоплаченных заказов.
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS orders_paid_at_idx
    ON orders (paid_at)
    WHERE payment_status = 'paid';

COMMENT ON INDEX orders_paid_at_idx IS 'Оплаченные заказы по времени оплаты (фоновый выпуск подарочных кодов)';

-- -----------------------------------------------------------------------------
-- Сид ключа настроек `gift` (политика выпуска подарочных кодов).
--
-- ON CONFLICT (setting_key) DO NOTHING обязателен и НИКАКОГО UPDATE: ключ может
-- уже существовать (магазин настроил политику в админке), а безусловная запись
-- затёрла бы выбор владельца при следующем накате.
--
-- Сеем только ПОВЕДЕНЧЕСКИЕ флаги, оба в значении «как ожидает владелец»:
-- код выпускается сам при оплате, обмен номинала разрешён. Список разделов
-- каталога (categorySlugs) в сид НЕ кладём осознанно: у каждого магазина он свой,
-- и платформенный дефаультный адрес живёт в коде (GIFT_SETTINGS_DEFAULTS), откуда
-- владелец переопределяет его формой. Так миграция остаётся нейтральной к нише.
-- -----------------------------------------------------------------------------
INSERT INTO shop_settings (setting_key, value)
VALUES ('gift', '{"autoIssue":true,"allowIssueOnGiftPaidOrder":true}'::jsonb)
ON CONFLICT (setting_key) DO NOTHING;

INSERT INTO schema_migrations (version, name)
VALUES ('0056', 'gift_auto_issue')
ON CONFLICT DO NOTHING;
