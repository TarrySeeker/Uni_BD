-- =============================================================================
-- 0060_cms_pages_nav.sql — признак «страница в боковом меню разделов» + порядок.
--
-- ЗАЧЕМ. Эталон carrerusse.com показывает у дополнительных страниц вертикальное
-- меню разделов слева (`.about__nav`: О нас / Доставка / Оплата / Политика /
-- FAQ / Оферта). На проде это были ЯКОРИ внутри одной страницы `/about`; у нас
-- каждая такая страница — отдельная CMS-запись со своим URL, SEO и переводом,
-- поэтому боковик стал навигацией ПО СТРАНИЦАМ.
--
-- Набор пунктов НЕЛЬЗЯ зашивать в код витрины (мультитенантность, ADR-003:
-- 1 магазин = 1 БД, но код общий): у следующего магазина другой состав страниц
-- или боковик не нужен вовсе. Поэтому источник — сами страницы:
--   • show_in_nav — владелец отмечает чекбоксом в карточке страницы;
--   • nav_order   — позиция в меню; NULL = «порядок не задан», такие пункты
--                   уходят в конец и сортируются по заголовку.
--
-- Обратная совместимость: show_in_nav NOT NULL DEFAULT false — существующие
-- страницы остаются вне боковика, пока владелец их не отметит; магазин, который
-- ничего не отметил, получает пустое меню, и витрина рендерит контент на всю
-- ширину (левая колонка не выводится вовсе).
--
-- Идемпотентно: ADD COLUMN IF NOT EXISTS; запись в schema_migrations
-- ON CONFLICT DO NOTHING. Таблично-уровневые GRANT покрывают новые колонки.
-- Мультитенантность: без tenant_id (ADR-003).
-- =============================================================================

ALTER TABLE cms_pages ADD COLUMN IF NOT EXISTS show_in_nav boolean NOT NULL DEFAULT false;
ALTER TABLE cms_pages ADD COLUMN IF NOT EXISTS nav_order   integer;

-- Частичный индекс: витрина при каждом рендере доп-страницы выбирает пункты
-- боковика (show_in_nav = true среди published). Строк с флагом единицы —
-- индекс крошечный, но убирает seq-scan по всем страницам магазина.
CREATE INDEX IF NOT EXISTS cms_pages_nav_idx
  ON cms_pages (nav_order NULLS LAST, title)
  WHERE show_in_nav;

INSERT INTO schema_migrations (version, name)
VALUES ('0060', 'cms_pages_nav')
ON CONFLICT DO NOTHING;
