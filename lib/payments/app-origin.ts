/**
 * ПУБЛИЧНЫЙ ORIGIN САМОГО ПРИЛОЖЕНИЯ (Admik) — адрес, по которому браузер покупателя
 * открывает страницы ЭТОГО приложения.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. При инициации платежа участвуют ДВА РАЗНЫХ адреса, и
 * путать их нельзя — у них разная природа, разный получатель и разный источник:
 *
 *   1) АДРЕС ВОЗВРАТА покупателя (`returnUrl`) → домен ВИТРИНЫ. Уезжает в платёжный
 *      шлюз и превращается в редирект покупателя С ЛЕГИТИМНОЙ ПЛАТЁЖНОЙ ФОРМЫ,
 *      поэтому его origin берётся ТОЛЬКО из доверенных настроек владельца
 *      (`lib/payments/return-url.ts`). Это защита от open redirect — ослаблять её
 *      нельзя ни при каких обстоятельствах.
 *
 *   2) АДРЕС DEMO-СТРАНИЦЫ оплаты (`baseOrigin`) → домен ЭТОГО приложения. Страницы
 *      `app/mock/<провайдер>/pay` физически лежат в приложении админки, а витрина —
 *      ОТДЕЛЬНЫЙ контейнер на ДРУГОМ хосте (`<домен>` против `admin.<домен>`,
 *      docker-compose). Подставить сюда origin витрины — значит увести demo-оплату
 *      на сайт, где такой страницы нет: покупатель жмёт «Оплатить» и получает 404.
 *      Ровно эта регрессия и чинится данным модулем.
 *
 * ЧЕМ РИСКУЕМ. `baseOrigin` попадает ТОЛЬКО в mock-ветку адаптеров (боевые
 * `initPayment` его игнорируют — ссылку на оплату даёт сам шлюз) и возвращается в
 * ответе ТОМУ ЖЕ вызывающему, который прислал запрос. Он не уезжает в шлюз и не
 * редиректит третьих лиц, поэтому недоверенный фолбэк на origin запроса здесь
 * допустим: подменивший заголовок «уводит» только сам себя. Для адреса возврата
 * такой фолбэк недопустим — см. return-url.ts.
 *
 * ИСТОЧНИКИ (по приоритету):
 *   1) `NEXT_PUBLIC_ADMIK_API_URL` — публичный адрес Admik из `.env` инстанса
 *      (`https://admin.<домен>`); тем же значением витрина собирается на клиент.
 *      Задаёт ВЛАДЕЛЕЦ, покупателем не управляемо. Мультитенантно, без хардкода.
 *   2) origin запроса (`X-Forwarded-Host`/`-Proto`, иначе `req.url`) — фолбэк для
 *      стендов, где переменная не задана или осталась нераскрытым плейсхолдером.
 *
 * Функции ЧИСТЫЕ и НЕ бросают: мисконфигурация не должна ронять инициацию платежа.
 */

import { normalizeOrigin } from './return-url';

/**
 * Имя переменной окружения с публичным адресом приложения. Читается ПО КЛЮЧУ, а не
 * как `process.env.NEXT_PUBLIC_...`: литеральное обращение Next.js подставляет на
 * этапе СБОРКИ, а нам нужно рантайм-значение из окружения контейнера.
 */
export const APP_ORIGIN_ENV_KEY = 'NEXT_PUBLIC_ADMIK_API_URL';

/**
 * Публичный origin приложения из env владельца либо null. Путь/хвостовой слэш
 * отбрасываются; нераскрытый плейсхолдер (`https://${ADMIN_DOMAIN}`) и мусор
 * отсекаются normalizeOrigin — тогда работает фолбэк на origin запроса.
 */
export function appOriginFromEnv(
  env: Record<string, string | undefined> = process.env,
): string | null {
  return normalizeOrigin(env[APP_ORIGIN_ENV_KEY]);
}

/**
 * Origin входящего запроса. За реверс-прокси (Caddy) `req.url` несёт ВНУТРЕННИЙ
 * адрес (`http://app:3000`), непригодный для браузера, поэтому сначала берём
 * `X-Forwarded-Host`/`-Proto` (первое значение списка).
 *
 * 🔴 НЕ ДОВЕРЕННЫЙ ИСТОЧНИК: заголовок производен от клиентского `Host`, Caddy его
 * ДОПИСЫВАЕТ, а не затирает — приложение не отличит свой от присланного
 * злоумышленником. Годится только для ссылки, которую получает сам вызывающий.
 */
export function requestOrigin(req: Request): string | undefined {
  const host = req.headers.get('x-forwarded-host');
  if (host) {
    const proto = (req.headers.get('x-forwarded-proto') ?? 'https').split(',')[0]!.trim();
    return normalizeOrigin(`${proto}://${host.split(',')[0]!.trim()}`) ?? undefined;
  }
  try {
    return normalizeOrigin(new URL(req.url).origin) ?? undefined;
  } catch {
    return undefined;
  }
}

/**
 * Origin для абсолютной ссылки на DEMO-страницу оплаты (`baseOrigin` адаптеров).
 * Настройка владельца приоритетнее заголовков запроса; без неё — origin запроса,
 * как было до появления пер-заказного адреса возврата. Origin ВИТРИНЫ сюда не
 * попадает по конструкции: у функции нет доступа к настройкам магазина.
 */
export function resolveMockPageOrigin(
  req: Request,
  env: Record<string, string | undefined> = process.env,
): string | undefined {
  return appOriginFromEnv(env) ?? requestOrigin(req);
}
