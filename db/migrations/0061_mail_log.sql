-- =============================================================================
-- 0061_mail_log.sql  (ПОЧТОВЫЙ МОДУЛЬ — журнал отправок писем)
--
-- ЗАЧЕМ ЖУРНАЛ, А НЕ «ОТПРАВИЛИ И ЗАБЫЛИ».
-- Письмо с кодом подарочного сертификата — это ДЕНЬГИ НА ПРЕДЪЯВИТЕЛЯ. До этой
-- волны покупатель получал код ТОЛЬКО на эфемерной странице успеха: закрыл
-- вкладку — потерял деньги, и у владельца не было ни следа, ни способа переслать.
-- Журнал даёт ровно две вещи, которых не хватало:
--   1) ФАКТ отправки (кому, что, когда, удалось ли) — иначе спор с покупателем
--      «мне ничего не пришло» неразрешим;
--   2) возможность ДОСЛАТЬ — кнопкой в админке и кроном (/api/cron/mail/retry-failed).
--
-- 🔴 ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ — ТЕЛА ПИСЬМА И КОДА СЕРТИФИКАТА.
-- Хранить отрендеренное письмо означало бы держать код на предъявителя ВТОРОЙ раз,
-- в таблице, которую читает любой оператор с правом на раздел «Письма», и тащить
-- его в дампы/бэкапы. Поэтому строка журнала — это МЕТАДАННЫЕ: адресат, тип
-- шаблона, язык, статус, попытки, ошибка, ссылка на заказ. Тело пересобирается
-- заново из заказа в момент досылки (тот же рендер, тот же актуальный код).
-- По той же причине здесь нет колонки subject_raw с подставленными данными
-- покупателя: тема хранится как есть (в ней кода нет), но она не источник правды.
--
-- ПОЧЕМУ status — text + CHECK, А НЕ ENUM: добавление значения в ENUM
-- (ALTER TYPE ... ADD VALUE) неаддитивно по §6.4/ADR-015, а расширение CHECK
-- требует owner-signed carve-out. Полный набор закладываем сразу:
--   'pending' — запись создана, отправка ещё идёт (краткоживущее состояние);
--   'sent'    — релей принял письмо (sent_at заполнен);
--   'failed'  — попытки исчерпаны; кандидат на досылку кроном/кнопкой;
--   'skipped' — отправка не выполнялась ОСОЗНАННО и это НЕ авария: почта магазина
--               не настроена (мультитенантность — SMTP есть не у каждого магазина),
--               либо у заказа нет адреса, либо адрес невалиден. Отдельный статус
--               нужен, чтобы крон не ретраил вечно то, что ретраить бессмысленно,
--               а владелец видел разницу между «релей отказал» и «почта выключена».
--
-- ССЫЛКА НА ЗАКАЗ — ON DELETE SET NULL, не CASCADE: журнал переживает удаление
-- заказа. Факт «мы отправляли код на этот адрес» — это доказательство, которое
-- не должно исчезать вместе с операционной записью.
--
-- Аддитивно и идемпотентно (проходит scripts/check-migrations.sh): только
-- CREATE TABLE/INDEX IF NOT EXISTS, никаких DROP/RENAME/смены типа.
--
-- НОМЕР 0061, А НЕ 0062: нумерация миграций в этом репозитории обязана быть
-- СПЛОШНОЙ — это требование восьми guard-тестов (tests/db/*-migrations.test.ts,
-- tests/settings/gift-migration.test.ts, tests/config/settings.test.ts), которые
-- сверяют список версий с последовательностью 0001..N без пропусков. Пропуск
-- 0061 «под будущую параллельную миграцию» валит их все: гэп в нумерации для
-- этого репозитория — не соглашение, а красный тест.
-- =============================================================================

CREATE TABLE IF NOT EXISTS mail_log (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Кому. citext — как orders.customer_email/customers.email: поиск «что мы
    -- слали на этот адрес» обязан быть регистронезависимым.
    recipient     citext      NOT NULL,

    -- Тип письма = идентификатор шаблона (gift_certificate, order_confirmation,
    -- cdek_delivered, …). НЕ CHECK-список: набор шаблонов живёт в коде
    -- (lib/mail/templates.ts) и расширяется без миграции; часть значений уже
    -- задана картой STATUS_TO_CLIENT_TEMPLATE модуля СДЭК.
    template      text        NOT NULL,

    -- Язык ПОКУПАТЕЛЯ, на котором письмо отрендерено (ru|en|fr|…). Хранится, чтобы
    -- досылка повторила тот же язык, а не язык оператора.
    locale        text,

    status        text        NOT NULL DEFAULT 'pending',

    -- Сколько раз реально дёргали релей по этой записи (внутренние ретраи + досылки).
    attempts      integer     NOT NULL DEFAULT 0,

    -- Последняя ошибка транспорта (текст SMTP/сети). Секретов не содержит: тело
    -- письма сюда не пишется, пароль SMTP в сообщение об ошибке не попадает.
    error         text,

    -- Тема письма — для узнаваемости строки в админке. Кода сертификата в теме нет
    -- по построению (см. шаблоны): тема говорит «ваш подарочный сертификат», но не
    -- называет сам код.
    subject       text,

    order_id      uuid REFERENCES orders(id) ON DELETE SET NULL,

    sent_at       timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT mail_log_status_chk
        CHECK (status IN ('pending', 'sent', 'failed', 'skipped'))
);

COMMENT ON TABLE  mail_log IS 'Журнал отправок писем: факт и метаданные. Тело письма и коды сертификатов здесь НЕ хранятся';
COMMENT ON COLUMN mail_log.template IS 'Идентификатор шаблона письма (lib/mail/templates.ts)';
COMMENT ON COLUMN mail_log.locale IS 'Язык покупателя, на котором отрендерено письмо';
COMMENT ON COLUMN mail_log.status IS 'pending|sent|failed|skipped (skipped — почта не настроена/нет адреса, это не авария)';
COMMENT ON COLUMN mail_log.attempts IS 'Сколько раз дёргали релей по этой записи';
COMMENT ON COLUMN mail_log.error IS 'Последняя ошибка транспорта (без тела письма и секретов)';

-- -----------------------------------------------------------------------------
-- Индексы.
-- -----------------------------------------------------------------------------

-- Раздел «Письма» в админке: список от новых к старым.
CREATE INDEX IF NOT EXISTS mail_log_created_at_idx ON mail_log (created_at DESC);

-- Выборка кандидатов на досылку (крон /api/cron/mail/retry-failed). ЧАСТИЧНЫЙ:
-- подавляющее большинство строк со временем станет 'sent', и полный индекс по
-- status рос бы впустую. Так планировщик получает прямой доступ ровно к тому
-- хвосту, который надо добрать.
CREATE INDEX IF NOT EXISTS mail_log_retryable_idx
    ON mail_log (created_at)
    WHERE status = 'failed';

COMMENT ON INDEX mail_log_retryable_idx IS 'Неотправленные письма для досылки кроном';

-- «Что мы слали по этому заказу» — карточка заказа и разбор споров.
CREATE INDEX IF NOT EXISTS mail_log_order_idx
    ON mail_log (order_id)
    WHERE order_id IS NOT NULL;

-- «Что мы слали на этот адрес» — поиск по адресату в разделе «Письма».
CREATE INDEX IF NOT EXISTS mail_log_recipient_idx ON mail_log (recipient);

INSERT INTO schema_migrations (version, name)
VALUES ('0061', 'mail_log')
ON CONFLICT DO NOTHING;
