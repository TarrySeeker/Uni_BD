/**
 * Подписи модулей платформы — КЛЮЧИ перевода (единый источник правды).
 *
 * Раньше подписи существовали в ДВУХ несогласованных местах:
 *   • MODULE_LABELS в форме модулей настроек — русские литералы, из-за чего экран
 *     /admin/settings показывал «Каталог», «Заказы», «Доставка» при локали en/fr
 *     (подтверждено живой проверкой стенда);
 *   • группа ключей roles.roleForm.modules.* — только 5 модулей из 9, поэтому
 *     группы прав news/reviews/account в форме роли печатали СЫРОЙ код модуля.
 * Оба места сведены сюда: одна карта модуль → ключ, один резолвер.
 *
 * Почему подписи модулей НЕ переиспользуют nav.*: модуль ≠ пункт меню. Модуль —
 * это переключаемая возможность платформы, и его выключение прячет НЕСКОЛЬКО
 * разделов сразу (orders → «Заказы» + «Промокоды» + «Сертификаты»), поэтому
 * подпись перечисляет состав («Заказы и промокоды») и называет внешнюю систему
 * («Доставка (СДЭК)», «Оплата (Т-Банк)») — владельцу важно понимать, ЧТО именно
 * он отключает в подтверждающем диалоге. Плюс `payments` и `account` вообще не
 * имеют одноимённого пункта меню, а nav.cdek («Доставка») не говорит о СДЭК.
 * Привязка к nav.* означала бы, что переименование пункта меню молча меняет текст
 * необратимого предупреждения — связь, которой быть не должно.
 */

import type { ModuleName } from './modules';

/** Модуль → ключ подписи в messages/{ru,en,fr}.json. */
export const MODULE_LABEL_KEYS: Readonly<Record<ModuleName, string>> = {
  catalog: 'modules.catalog',
  orders: 'modules.orders',
  cdek: 'modules.cdek',
  cms: 'modules.cms',
  payments: 'modules.payments',
  news: 'modules.news',
  reviews: 'modules.reviews',
  account: 'modules.account',
};

/**
 * Псевдомодуль `core` — группа сквозных прав (пользователи, роли, аудит,
 * настройки, i18n). Не переключается, но нуждается в подписи в форме роли.
 */
export const CORE_LABEL_KEY = 'modules.core';

/**
 * Подпись модуля. Фолбэк — сам код модуля, если он неизвестен (интерфейс не
 * падает на модуле, добавленном в БД раньше, чем в каталог сообщений).
 * Паттерн передачи `t` — как в lib/admin/audit-labels.ts и lib/auth/permissions.ts.
 */
export function moduleLabel(module: string, t: (key: string) => string): string {
  if (module === 'core') return t(CORE_LABEL_KEY);
  const key = MODULE_LABEL_KEYS[module as ModuleName];
  return key ? t(key) : module;
}
