import { describe, expect, it } from 'vitest';

import { uniqueSizes } from '@/lib/catalog/repository';

// ЮНИТ: схлопывание меток размеров для фасета сетки каталога — без БД.
//
// ЗАЧЕМ ВТОРОЙ РУБЕЖ ПОВЕРХ SQL: SQL в listProducts уже группирует по имени, но
// фасет каталога сравнивает метки ТОЧНОЙ строкой, и любой просочившийся дубль
// («42» и «42 ») рисует в фильтре две кнопки на один размер. Проверка дешёвая,
// цена промаха — видимый мусор в фильтре.

describe('uniqueSizes', () => {
  it('схлопывает дубли, сохраняя порядок первого появления', () => {
    // Матрица «цвет × размер»: 2 цвета × 3 размера дают 6 вариантов и 3 метки.
    expect(uniqueSizes(['42', '44', '46', '42', '44', '46'])).toEqual([
      '42',
      '44',
      '46',
    ]);
  });

  it('обрезает пробелы и считает «42 » тем же размером, что «42»', () => {
    expect(uniqueSizes([' 42 ', '42', '44 '])).toEqual(['42', '44']);
  });

  it('отбрасывает пустые метки и null/undefined (вариант без имени — не размер)', () => {
    expect(uniqueSizes(['S', '', null, undefined, '   ', 'M'])).toEqual([
      'S',
      'M',
    ]);
  });

  it('пустой вход → пустой массив (товар без вариантов)', () => {
    expect(uniqueSizes([])).toEqual([]);
  });

  it('не сортирует: порядок задаёт SQL (min(sort) метки), а не алфавит', () => {
    // Алфавитная сортировка поставила бы «10» перед «9» — размерный ряд
    // обязан остаться в порядке сортировки вариантов.
    expect(uniqueSizes(['S', 'M', 'L', 'XL'])).toEqual(['S', 'M', 'L', 'XL']);
  });
});
