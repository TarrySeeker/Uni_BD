/**
 * Нормализация кода подарочного сертификата, введённого покупателем.
 *
 * ФАКТЫ, из которых выведено правило (проверено по коду платформы, не по догадке):
 *   1. `gift_certificates.code` — тип `citext` (миграция 0039) с UNIQUE-индексом,
 *      а поиск точный: `findByCode` → `WHERE code = $1`. Значит РЕГИСТР не важен,
 *      а любой лишний/пропущенный символ — «сертификат не найден».
 *   2. Код, который магазин ВЫДАЁТ покупателю (автовыпуск и покупка сертификата),
 *      делает `randomGiftCode()`: 16 символов алфавита Crockford base32,
 *      сгруппированных по 4 через ДЕФИС — `XXXX-XXXX-XXXX-XXXX`. Ровно в этом
 *      виде код лежит в БД, печатается на /cart/success и копируется кнопкой.
 *      → дефис является ЧАСТЬЮ хранимого кода; «убрать разделители» = сломать
 *        все живые сертификаты. Нормализация обратная: разделители ВОССТАНАВЛИВАЕМ.
 *   3. Код ручного выпуска по позиции заказа — `buildGiftCodeForOrderItem()` =
 *      `НОМЕР-ЗАКАЗА-XXXXXX`, а номер заказа сам дефисный (`[ПРЕФИКС-]ГОД-NNNNNN`).
 *      У такого кода полезная нагрузка тоже бывает ровно 16 символов Crockford
 *      («2026-000123-A1B2C3»), но группы НЕ по 4 → слепая перегруппировка убила бы
 *      и его. Поэтому группировку применяем ТОЛЬКО к каноническому виду.
 *   4. Админ вводит код руками свободным текстом (`giftCodeSchema` = trim, 1..64):
 *      в коде могут быть значащие пробелы и любые разделители → такие строки
 *      отдаём как есть (только trim).
 *
 * Итого: приводим к хранимому виду ровно те вводы, которые однозначно являются
 * каноническим кодом выпуска (16 символов Crockford base32 слитно ИЛИ группами
 * ровно по 4 через любые пробелы/тире), всё остальное — только trim.
 *
 * ⚠️ Единственный остаточный случай: если админ ВРУЧНУЮ создаст код из ровно 16
 * символов Crockford base32 БЕЗ разделителей (напр. «ABCD1234EFGH5678»), ввод
 * такого кода будет приведён к «ABCD-1234-EFGH-5678» и не найдётся. Выпускаемые
 * платформой коды всегда содержат дефисы, поэтому цена этого случая — договорённость
 * «ручные коды делаем с разделителем или не 16 символов», а выигрыш — работающий
 * ввод для всех кодов, которые магазин действительно выдаёт покупателям.
 */

/**
 * Разделители, которые покупатель реально приносит в поле: любые пробелы
 * (включая NBSP и узкий NBSP — их вставляют письма/PDF), ASCII-дефис, юникодные
 * тире U+2010…U+2015 и минус U+2212 (автозамена в Word/почтовых клиентах).
 */
const SEPARATORS = /[-\s\u2010-\u2015\u2212]+/;

/** Алфавит Crockford base32 (без I, L, O, U) — тот же, что у randomGiftCode(). */
const CROCKFORD_ONLY = /^[0-9A-HJKMNP-TV-Z]+$/;

/** Длина полезной нагрузки выпускаемого кода: 10 байт энтропии = 16 символов. */
const PAYLOAD_LENGTH = 16;

/** Размер группы в печатном виде кода: XXXX-XXXX-XXXX-XXXX. */
const GROUP_SIZE = 4;

/**
 * Ввод покупателя → код в том виде, в котором он хранится в БД.
 * Пустая строка означает «код не введён».
 */
export function normalizeGiftCode(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed === '') return '';

  const groups = trimmed.split(SEPARATORS).filter((g) => g !== '');
  const payload = groups.join('').toUpperCase();

  // Не канонический код выпуска → ни одного символа не меняем (только trim):
  // это либо код ручного выпуска со значащими разделителями, либо код админа.
  if (payload.length !== PAYLOAD_LENGTH || !CROCKFORD_ONLY.test(payload)) return trimmed;

  // Канонический код: набран слитно ИЛИ группами ровно по 4 (разделитель любой).
  const grouped =
    groups.length === PAYLOAD_LENGTH / GROUP_SIZE &&
    groups.every((g) => g.length === GROUP_SIZE);
  if (groups.length !== 1 && !grouped) return trimmed;

  return (payload.match(/.{4}/g) ?? [payload]).join('-');
}
