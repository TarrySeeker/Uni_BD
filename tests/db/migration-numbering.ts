import { expect } from 'vitest';

/**
 * Общий помощник для тестов, которые раньше требовали СПЛОШНОЙ нумерации
 * миграций (`versions === ['0001','0002',…]`).
 *
 * Почему требование снято. Кит живёт двумя ветками: freeLK (без личного
 * кабинета покупателя, основная линия) и LK (то же + кабинет). Миграции
 * кабинета 0034_customer_accounts…0037_customer_auth_tokens существуют ТОЛЬКО
 * в LK и в freeLK попадать не должны, поэтому здесь на их месте законный и
 * постоянный разрыв 0033 → 0038. Сплошная нумерация структурно несовместима с
 * такой моделью: любая правка платформы поверх ветки-без-кабинета снова его
 * воспроизведёт.
 *
 * Почему разрыв безопасен. Накат (`lib/db/migrate`) сортирует файлы
 * лексикографически по имени, а не по «счётчику от единицы»: пропущенный номер
 * не влияет ни на порядок, ни на полноту наката. Значение имеют только два
 * инварианта, которые и проверяются ниже, — их нарушение реально сломает накат:
 *
 *   1) формат версии ровно NNNN (4 цифры). «12» вместо «0012» встанет в
 *      лексикографической сортировке не туда, где его ждут («12» > «0099»);
 *   2) строгая монотонность. Одинаковые версии в двух файлах = недетерминированный
 *      порядок наката и коллизия ключа в schema_migrations.
 *
 * Содержательные утверждения о КОНКРЕТНЫХ ожидаемых версиях (`toContain('0019')`
 * и т.п.) этот помощник не заменяет — они остаются в вызывающих тестах.
 */
export function expectVersionsStrictlyIncreasing(versions: readonly string[]): void {
  for (const version of versions) {
    expect(version, `версия «${version}» не в формате NNNN`).toMatch(/^\d{4}$/);
  }

  // Сравнение строк корректно именно из-за фиксированной ширины NNNN (проверена выше).
  // Строгое «>» заодно отсекает дубликаты версий, а не только обратный порядок.
  for (let i = 1; i < versions.length; i += 1) {
    expect(
      versions[i] > versions[i - 1],
      `версии не строго возрастают: «${versions[i - 1]}» → «${versions[i]}»`,
    ).toBe(true);
  }
}
